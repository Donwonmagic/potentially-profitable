#!/usr/bin/env node
// Re-stamp the "Recently added" rail inside glossary/index.html (and
// the ES mirror) between
//   <!-- glossary-recent:start --> ... <!-- glossary-recent:end -->
// sentinels. Source of truth is data/glossary-added.json — the rail
// shows the first `display_count` entries (newest-first) with each
// term's headword pulled live from glossary/<slug>/index.html so a
// rename in the source doesn't drift. Idempotent; safe to re-run on
// every build.
//
// The rail itself is a compact section that announces the most-recent
// additions to a returning reader, so the 30+ recently-added terms
// (photography, hours, finance, brand-design clusters) don't sit
// invisible until the reader scrolls past their section.
//
//   node scripts/inject-glossary-recent.mjs           # rewrites in place
//   node scripts/inject-glossary-recent.mjs --check   # exits non-zero if anything would change

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const REPO       = path.resolve(path.dirname(__filename), '..');
const checkOnly  = process.argv.includes('--check');

const SENTINEL_OPEN  = '<!-- glossary-recent:start (generated by scripts/inject-glossary-recent.mjs) -->';
const SENTINEL_CLOSE = '<!-- glossary-recent:end -->';
const SENTINEL_RE = new RegExp(
  `${SENTINEL_OPEN.replace(/[-/\\^$*+?.()|[\]{}]/g, '\\$&')}[\\s\\S]*?${SENTINEL_CLOSE.replace(/[-/\\^$*+?.()|[\]{}]/g, '\\$&')}`
);

const data = JSON.parse(fs.readFileSync(path.join(REPO, 'data', 'glossary-added.json'), 'utf8'));
const displayCount = data.display_count || 6;

function termHead(locale, slug) {
  // Read the term page's <h1 class="term-h1"> for the localised
  // headword. Falls back to the slug if the file's missing or h1
  // isn't found.
  const fp = locale === 'en'
    ? path.join(REPO, 'glossary',    slug, 'index.html')
    : path.join(REPO, 'es/glossary', slug, 'index.html');
  if (!fs.existsSync(fp)) return null;
  const html = fs.readFileSync(fp, 'utf8');
  const m = html.match(/<h1 class="term-h1">([\s\S]*?)<\/h1>/);
  if (!m) return slug;
  return m[1]
    .replace(/<[^>]+>/g, '')
    .replace(/&amp;/g, '&').replace(/&lt;/g,'<').replace(/&gt;/g,'>')
    .replace(/&quot;/g,'"').replace(/&#39;/g,"'")
    .replace(/\s+/g, ' ')
    .trim();
}

function escAttr(s){ return String(s).replace(/&/g,'&amp;').replace(/"/g,'&quot;').replace(/</g,'&lt;').replace(/>/g,'&gt;'); }
function escText(s){ return String(s).replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;'); }

// Format ISO date (YYYY-MM-DD) into the locale's preferred display.
// EN: "Apr 26", ES: "26 abr". Returns "" on parse failure.
function fmtDate(iso, locale){
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(iso || '');
  if (!m) return '';
  const months = locale === 'es'
    ? ['ene','feb','mar','abr','may','jun','jul','ago','sep','oct','nov','dic']
    : ['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec'];
  const mon = months[parseInt(m[2], 10) - 1];
  const day = String(parseInt(m[3], 10));
  return locale === 'es' ? `${day} ${mon}` : `${mon} ${day}`;
}

function fmtUpdated(iso, locale){
  const m = /^(\d{4})-(\d{2})-/.exec(iso || '');
  if (!m) return '';
  const fullMonths = locale === 'es'
    ? ['enero','febrero','marzo','abril','mayo','junio','julio','agosto','septiembre','octubre','noviembre','diciembre']
    : ['January','February','March','April','May','June','July','August','September','October','November','December'];
  const mon = fullMonths[parseInt(m[2], 10) - 1];
  return locale === 'es' ? `${mon} ${m[1]}` : `${mon} ${m[1]}`;
}

function renderRail(locale){
  const heading = locale === 'es' ? 'Añadido recientemente' : 'Recently added';
  const updatedLabel = locale === 'es' ? 'Actualizado' : 'Updated';
  const moreLabel = locale === 'es'
    ? 'Mira todas las definiciones nuevas'
    : 'See every new definition';
  const updatedHuman = fmtUpdated(data.updated, locale);

  const items = [];
  for (const entry of (data.added || [])) {
    if (items.length >= displayCount) break;
    const head = termHead(locale, entry.slug);
    if (!head) continue; // skip orphan slugs silently
    const href = locale === 'es' ? `/es/glossary/${entry.slug}/` : `/glossary/${entry.slug}/`;
    const date = fmtDate(entry.date, locale);
    items.push(`        <li>
          <a class="gloss-recent__card" href="${escAttr(href)}">
            ${date ? `<span class="gloss-recent__date">${escText(date)}</span>` : ''}
            <span class="gloss-recent__head">${escText(head)}</span>
            ${entry.note ? `<span class="gloss-recent__note">${escText(entry.note)}</span>` : ''}
          </a>
        </li>`);
  }

  if (!items.length) return `${SENTINEL_OPEN}\n${SENTINEL_CLOSE}`;

  return `${SENTINEL_OPEN}
<aside class="container gloss-recent" aria-labelledby="gloss-recent-h">
  <header class="gloss-recent__head-row">
    <span class="eyebrow">${escText(heading)}</span>
    <h2 id="gloss-recent-h">${escText(updatedLabel)} ${escText(updatedHuman)}.</h2>
  </header>
  <ul class="gloss-recent__list">
${items.join('\n')}
  </ul>
</aside>
${SENTINEL_CLOSE}`;
}

const TARGETS = [
  { locale: 'en', file: 'glossary/index.html'    },
  { locale: 'es', file: 'es/glossary/index.html' },
];

let touched = 0;
for (const target of TARGETS) {
  const abs = path.join(REPO, target.file);
  if (!fs.existsSync(abs)) { console.warn(`missing: ${target.file}`); continue; }
  const src  = fs.readFileSync(abs, 'utf8');
  if (!SENTINEL_RE.test(src)) {
    console.error(`${target.file} is missing the glossary-recent sentinels.`);
    process.exit(2);
  }
  const next = src.replace(SENTINEL_RE, renderRail(target.locale));
  if (next === src) {
    console.log(`${target.file}: no changes.`);
    continue;
  }
  if (checkOnly) {
    console.error(`${target.file}: would change.`);
    process.exit(1);
  }
  fs.writeFileSync(abs, next);
  touched++;
  console.log(`${target.file}: stamped.`);
}

if (!checkOnly) {
  console.log(`\nUpdated ${touched} of ${TARGETS.length} glossary index file(s).`);
}
