#!/usr/bin/env node
/**
 * Article skeleton generator — emits the full HTML wrapper for a new
 * blog post given a JSON brief. Used during the May-2026 long-tail
 * publication wave to avoid hand-typing the same 100 lines of head
 * boilerplate per article.
 *
 * Usage:
 *   node scripts/new-article-skeleton.mjs <brief.json>
 *
 * Brief shape (all required unless noted):
 *   {
 *     "locale":          "en" | "es",
 *     "slug":            "kebab-case-slug",
 *     "title":           "Article title (used in <title>, og:title, h1, schema)",
 *     "h1_main":         "First part of h1",         // before the italic span
 *     "h1_italic":       "italic part",              // optional accent
 *     "h1_tail":         "rest after italic.",       // optional, ends with period
 *     "description":     "Meta description / og:description / abstract",
 *     "og_image_slug":   "blog-foo-bar",             // resolves to /brand/og/<slug>.png
 *     "published":       "2026-05-10T11:30:00-04:00",
 *     "eyebrow":         "Op-ed · May 10, 2026 · 7 min read",
 *     "breadcrumb_tail": "Short breadcrumb label",
 *     "subtitle":        "The 18px subhead paragraph below the h1.",
 *     "body_html":       "<p>...</p><h2>...</h2><p>...</p>...",
 *     "post_end_cta": {
 *       "headline": "...",
 *       "body":     "...",
 *       "button":   "Run the audit",
 *       "href":     "/services/audit/?from=blog%2F<slug>"
 *     },
 *     "smart_next": {
 *       "read_label":  "...",
 *       "read_href":   "...",
 *       "try_label":   "...",
 *       "try_href":    "...",      // tool URLs accept intent=watch
 *       "topic_slug":  "<slug>"     // for /window/?topic=...
 *     }
 *   }
 *
 * Writes:  blog/<slug>/index.html  (en)
 *      or  es/blog/<slug>/index.html  (es)
 *
 * After running this, also:
 *   1. Add the EN+ES OG card entries to brand/og/cards.json
 *   2. Run node scripts/build-og-cards.mjs <og_image_slug>
 *   3. Update data/i18n-slug-map.json (for translated pairs)
 *   4. Run node scripts/sync-includes.mjs
 *   5. Run node scripts/stamp-hreflang.mjs
 *   6. Run node scripts/build-site-counts.mjs --update
 *   7. Run node scripts/build-sitemap.mjs + build-rss.mjs + build-llms-txt.mjs
 *   8. Run node scripts/inject-smart-next-cta.mjs + inject-hub-collection-schema.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const REPO = path.resolve(path.dirname(__filename), "..");

const BRIEF_PATH = process.argv[2];
if (!BRIEF_PATH) {
  console.error("Usage: node scripts/new-article-skeleton.mjs <brief.json>");
  process.exit(1);
}

const brief = JSON.parse(fs.readFileSync(BRIEF_PATH, "utf8"));
const {
  locale, slug, title, h1_main, h1_italic = "", h1_tail = "",
  description, og_image_slug, published, eyebrow, breadcrumb_tail,
  subtitle, body_html, post_end_cta, smart_next
} = brief;

const isES = locale === "es";
const dirRoot = isES ? `es/blog/${slug}` : `blog/${slug}`;
const outDir = path.join(REPO, dirRoot);
const canonicalPath = isES
  ? `/es/blog/${slug}/`
  : `/blog/${slug}/`;
const canonicalUrl = `https://muntin.digital${canonicalPath}`;

const breadcrumbHomeLabel = isES ? "Inicio" : "Home";
const breadcrumbArticlesLabel = isES ? "Artículos" : "Articles";
const breadcrumbHomeHref = isES ? "/es/" : "/";
const breadcrumbArticlesHref = isES ? "/es/blog/" : "/blog/";
const skipLinkLabel = isES ? "Saltar al contenido principal" : "Skip to main content";
const listenLabel = isES ? "Escuchar este artículo" : "Listen to this article";
const moreLibraryLabel = isES ? "Más de la biblioteca." : "More from the library.";
const smartNextHeader = isES ? "Qué hacer después" : "What to do next";
const readVerb = isES ? "Leer:" : "Read:";
const tryVerb = isES ? "Probar:" : "Try:";
const noteVerb = isES ? "O envíale una nota a Don:" : "Or send Don a note:";

const windowHref = isES ? `/es/window/?topic=${smart_next.topic_slug}` : `/window/?topic=${smart_next.topic_slug}`;

const ogImageUrl = `https://muntin.digital/brand/og/${og_image_slug}.png`;
const ogLocale = isES ? "es_ES" : "en_US";
const inLang = isES ? "es-ES" : "en-US";

