#!/usr/bin/env node
// Stamp <link rel="alternate" hreflang="..."> tags into every HTML page.
//
// Why this is a one-off rather than part of the build pipeline:
// the hreflang block lives inside <head>, is idempotent, and almost
// never changes. Running it during the build would re-parse and re-
// write every page on every deploy for a zero-diff outcome. A manual
// stamp committed to source keeps diffs reviewable and lets individual
// pages override the default block if they ever need to.
//
// Safe to re-run: the script detects its own marker comment and
// replaces the block rather than duplicating it.
//
//   node scripts/stamp-hreflang.mjs         # rewrite in place
//   node scripts/stamp-hreflang.mjs --check # exit non-zero if changes
//
// Skips /blog/* (blog translation is handled in a sibling repo and
// needs its own alternates wired later) and the tool-utility pages
// under /tools/* except the hub itself, which are not yet translated.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const repoRoot   = path.resolve(path.dirname(__filename), '..');
const checkOnly  = process.argv.includes('--check');

const BASE = 'https://muntin.digital';
const MARK_OPEN  = '<!-- i18n:hreflang START (generated by scripts/stamp-hreflang.mjs) -->';
const MARK_CLOSE = '<!-- i18n:hreflang END -->';
const BLOCK_RE   = /<!-- i18n:hreflang START[\s\S]*?<!-- i18n:hreflang END -->\n?/;

// The script walks the repo. For every .html file that has a
// <link rel="canonical" href=".../X/"> or analogous path signal, it
// computes the EN canonical path (its own URL pretty form) and the ES
// counterpart under /es/, and stamps a block of alternates.

const SKIP_DIRS = new Set([
  '_includes', 'node_modules', '.git', '.github', 'dist', '.wrangler',
  'docs', 'src', 'brand', 'assets', 'scripts'
]);

// Blog posts are NOT skipped — they get their own hreflang block
// pointing at /es/blog/<slug>/ counterparts. The Spanish blog content
// itself is authored in a sibling repo ("improve blog audio") and
// merged into this dist/ at deploy time. Until those Spanish pages
// land, the alternate URL may 404 temporarily; Google tolerates that
// in the interim as long as the alternate is declared consistently
// on both sides once they ship.
//
// Auto-generated landing pages (cuisine + theme story pages) ARE
// skipped — their generator already emits hreflang + og:locale tags
// inside the page <head>. Stamping a second block here would duplicate
// the alternates and cause the generator's idempotency check to fail.
const SKIP_PATH_PREFIXES = [
  'library/menu-design-cuisines/',
  'library/menu-design-themes/',
  'es/library/menu-design-cuisines/',
  'es/library/menu-design-themes/',
  // Ingredient-yield pages — build-ingredient-yield-pages.mjs emits its
  // own hreflang + og:locale block in the page <head>, same as the
  // cuisine/theme generators above. Stamping a second block here would
  // orphan the generator's lines after the sentinel.
  'library/ingredient-yields/',
  'es/library/ingredient-yields/',
  // Cost-index pages — build-cost-index-pages.mjs emits its own hreflang
  // + og:locale block, same pattern as the generators above.
  'cost-index/',
  'es/cost-index/',
  // Open-data hub — emitted by build-cost-index-pages.mjs (emitOpenHub /
  // emitSeasonalityHub) with the same inline hreflang, so skip it here too.
  'open/',
  'es/open/'
];

function collectHtml(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.')) continue;
    if (entry.isDirectory()) {
      if (SKIP_DIRS.has(entry.name)) continue;
      collectHtml(path.join(dir, entry.name), out);
    } else if (entry.isFile() && entry.name.endsWith('.html')) {
      out.push(path.join(dir, entry.name));
    }
  }
  return out;
}

// Derive the site-relative pretty URL for a file on disk. Mirrors the
// same convention we use elsewhere: directory-style URLs for
// /foo/index.html → "/foo/", and filename-form for /terms.html →
// "/terms.html". Root index is "/".
function prettyPathFor(relPath) {
  const posix = relPath.split(path.sep).join('/');
  if (posix === 'index.html') return '/';
  if (posix.endsWith('/index.html')) return '/' + posix.slice(0, -'index.html'.length);
  return '/' + posix;
}

// For a page's own EN URL, compute { en, es, xDefault } absolute URLs
// for the alternates block. EN pages point es → /es<path>; ES pages
// already under /es/ are not stamped by this script (they inherit
// their own block when authored).
//
// Hreflang must point at a *reachable* URL. If the ES counterpart
// doesn't exist on disk, we omit the es alternate rather than declare
// a phantom 404. Google ignores one-way claims; a missing alternate is
// safer than a stale one.
// Per-locale slug-map for the blog. Without this, /blog/<en-slug>/ would
// emit hreflang="es" → /es/blog/<en-slug>/ which 404s for translated-slug
// ES posts (e.g. /es/blog/cuanto-cuesta-... is the real ES counterpart of
// /blog/how-much-does-a-custom-restaurant-website-cost-in-2026/, not a
// /es/blog/<same-EN-slug>/ that doesn't exist). Adding a translated post
// is two-step: drop the file into /es/blog/<es-slug>/ AND add an entry to
// data/i18n-slug-map.json's "blog" map, then re-run this script.
const slugMapPath = path.join(repoRoot, 'data', 'i18n-slug-map.json');
let slugMap = { blog: {}, library: {}, esOriginal: [] };
try {
  slugMap = JSON.parse(fs.readFileSync(slugMapPath, 'utf8'));
  if (!slugMap.blog) slugMap.blog = {};
  if (!slugMap.library) slugMap.library = {};
  if (!slugMap.esOriginal) slugMap.esOriginal = [];
} catch (_) {
  // Missing or unreadable slug-map: behave as if empty. Pages still
  // get the default /es<path>/ alternate when it exists on disk.
}

function alternatesFor(enPath, repoRoot) {
  // Default ES counterpart is the EN path mirrored under /es/. For
  // blog posts, prefer the slug-map override so EN→ES hreflang points
  // at the actual translated URL.
  let esPath;
  const blogMatch = enPath.match(/^\/blog\/([^/]+)\/$/);
  const libMatch = enPath.match(/^\/library\/([^/]+)\/$/);
  if (blogMatch && slugMap.blog && slugMap.blog[blogMatch[1]]) {
    esPath = `/es/blog/${slugMap.blog[blogMatch[1]]}/`;
  } else if (libMatch && slugMap.library && slugMap.library[libMatch[1]]) {
    // Library articles with a translated ES slug (e.g. keep-plate-cost-honest
    // → costo-del-plato-cuando-cambian-los-precios). Without this, the EN page
    // would point hreflang="es" at /es/library/<same-en-slug>/, which doesn't
    // exist, so the alternate gets dropped — leaving a one-way hreflang pair.
    esPath = `/es/library/${slugMap.library[libMatch[1]]}/`;
  } else {
    esPath = enPath === '/' ? '/es/' : `/es${enPath}`;
  }
  const esExists = (() => {
    if (!repoRoot) return true; // back-compat: fall through if no root
    // Map a pretty path back to the file on disk.
    const rel = esPath === '/es/' ? 'es/index.html' : (esPath.slice(1) + (esPath.endsWith('/') ? 'index.html' : ''));
    const candidate = path.join(repoRoot, rel);
    try { return fs.existsSync(candidate); } catch { return false; }
  })();
  return {
    en: `${BASE}${enPath}`,
    es: esExists ? `${BASE}${esPath}` : null,
    xDefault: `${BASE}${enPath}`,
    esExists,
  };
}

function renderBlock(alts) {
  const lines = [
    MARK_OPEN,
    `<link rel="alternate" hreflang="en" href="${alts.en}" />`,
  ];
  if (alts.es) lines.push(`<link rel="alternate" hreflang="es" href="${alts.es}" />`);
  lines.push(`<link rel="alternate" hreflang="x-default" href="${alts.xDefault}" />`);
  lines.push('<meta property="og:locale" content="en_US" />');
  if (alts.es) lines.push('<meta property="og:locale:alternate" content="es_US" />');
  lines.push(MARK_CLOSE);
  return lines.join('\n') + '\n';
}

let changed = 0;
let skipped = 0;
const problems = [];

for (const file of collectHtml(repoRoot)) {
  const rel = path.relative(repoRoot, file);
  const posix = rel.split(path.sep).join('/');
  if (SKIP_PATH_PREFIXES.some((p) => posix.startsWith(p))) { skipped++; continue; }
  if (posix.startsWith('es/')) { skipped++; continue; }

  const src = fs.readFileSync(file, 'utf8');

  // The block is anchored by <link rel="canonical"> so it always sits
  // next to the canonical URL. Pages without a canonical tag are a
  // bug we want to see, so we log and continue rather than silently
  // skipping.
  const canonRe = /<link\s+rel="canonical"[^>]*>\n?/i;
  if (!canonRe.test(src)) {
    problems.push(`${rel}: no <link rel="canonical">, skipped`);
    skipped++;
    continue;
  }

  const alts = alternatesFor(prettyPathFor(rel), repoRoot);
  const block = renderBlock(alts);

  let next;
  if (BLOCK_RE.test(src)) {
    next = src.replace(BLOCK_RE, block);
  } else {
    next = src.replace(canonRe, (m) => m + block);
  }

  if (next !== src) {
    if (!checkOnly) fs.writeFileSync(file, next);
    changed++;
    console.log(`${checkOnly ? 'would update' : 'updated'}: ${rel}`);
  }
}

if (problems.length) {
  console.warn('\nwarnings:');
  for (const p of problems) console.warn(`  ${p}`);
}

console.log(`\n${checkOnly ? 'would update' : 'updated'} ${changed} file(s), skipped ${skipped}.`);

if (checkOnly && changed > 0) process.exit(1);
