#!/usr/bin/env node
// Render the restaurant checklist page to a static PDF that lives
// alongside the page and is linked as a direct download from the
// "Save it for later" section.
//
// Run this whenever the checklist content or the print CSS changes:
//
//   node scripts/render-checklist-pdfs.mjs
//
// Starts a short-lived static server on port 8734, renders the page
// with Puppeteer's print pipeline (@media print CSS + headerTemplate/
// footerTemplate running footer), writes a Letter-size PDF next to
// the source HTML, then shuts the server down.
//
// The `targets` array stays multi-entry even with one item so a
// future vertical can re-plug in without refactoring the render loop.
//
// Puppeteer draws the running footer via footerTemplate rather than
// CSS position:fixed — Chrome's print engine doesn't reserve page
// space for position:fixed content, so a CSS-only footer would overlay
// body text at the page break.

import { spawn } from 'node:child_process';
import { writeFileSync, existsSync } from 'node:fs';
import { setTimeout as sleep } from 'node:timers/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import puppeteer from 'puppeteer';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const PORT = 8734;
const BASE = `http://127.0.0.1:${PORT}`;

// Two output targets: the original English PDF and a Spanish sibling
// generated by driving the same page with ?lang=es. The runtime
// translator inside the page swaps every data-tr element before
// print, so the two PDFs share identical layout + print CSS and
// differ only in copy. The Spanish filename uses the "-es" suffix
// so server-side link rewriting (and the in-page toggle) can point
// Spanish users at it without a separate source HTML file.
const targets = [
  {
    url: `${BASE}/resources/restaurant-website-checklist/?lang=en`,
    out: 'resources/restaurant-website-checklist/muntin-restaurant-website-checklist.pdf',
    lang: 'en',
  },
  {
    url: `${BASE}/resources/restaurant-website-checklist/?lang=es`,
    out: 'resources/restaurant-website-checklist/muntin-restaurant-website-checklist-es.pdf',
    lang: 'es',
  },
];

// Running footer: attribution + Score fill-in + double rule.
// Rendered by Chrome in the reserved bottom page margin, so it sits
// below body content on every page without overlapping.
// Footer template factory: identical layout per language, but the
// "Score" fill-in label localizes so a printed Spanish checklist
// doesn't mix English chrome into an otherwise all-Spanish sheet.
function footerFor(lang) {
  const scoreLabel = lang === 'es' ? 'Puntuaci\u00f3n' : 'Score';
  return `
<style>
  .muntin-foot {
    font-family: Inter, -apple-system, BlinkMacSystemFont, "Helvetica Neue", Arial, sans-serif;
    font-size: 7.5pt;
    letter-spacing: 0.18em;
    text-transform: uppercase;
    color: #555;
    width: 100%;
    padding: 6pt 0.55in 0;
    margin: 0 auto;
    border-top: 3pt double #111;
    text-align: center;
    -webkit-print-color-adjust: exact;
    box-sizing: border-box;
  }
  .muntin-foot .sep { padding: 0 10pt; }
  .muntin-foot .score-line {
    display: inline-block;
    width: 90pt;
    border-bottom: 0.8pt solid #111;
    vertical-align: -1pt;
    margin-left: 6pt;
    height: 10pt;
  }
</style>
<div class="muntin-foot">
  Muntin Digital<span class="sep">&middot;</span>muntin.digital<span class="sep">&middot;</span>${scoreLabel}<span class="score-line"></span>
</div>`;
}
const HEADER = '<span></span>'; // empty — suppress Chrome's default date/URL stamp

async function main() {
  // 1. Start a simple static server from the repo root.
  const server = spawn('python3', ['-m', 'http.server', String(PORT)], {
    cwd: ROOT,
    stdio: ['ignore', 'ignore', 'ignore'],
  });
  // Give the server a moment to bind.
  await sleep(800);

  try {
    const browser = await puppeteer.launch({
      headless: 'new',
      args: ['--no-sandbox', '--disable-setuid-sandbox', '--font-render-hinting=none'],
    });

    for (const t of targets) {
      const page = await browser.newPage();
      await page.emulateMediaType('print');
      await page.goto(t.url, { waitUntil: 'networkidle0', timeout: 30000 });
      // Let the page's self-hosted webfonts finish loading AND give
      // the data-tr runtime translator a tick to swap strings into
      // Spanish before Chrome snapshots the DOM for print.
      await page.evaluateHandle('document.fonts.ready');
      if (t.lang === 'es') {
        await page.evaluate(() => {
          if (typeof window.__muntinTranslateChecklist === 'function') {
            window.__muntinTranslateChecklist();
          }
        });
      }

      const pdf = await page.pdf({
        format: 'Letter',
        printBackground: true,
        displayHeaderFooter: true,
        headerTemplate: HEADER,
        footerTemplate: footerFor(t.lang || 'en'),
        // Bottom margin reserves the footer strip; keep in sync with
        // the running footer height above.
        margin: { top: '0.4in', bottom: '0.8in', left: '0.55in', right: '0.55in' },
      });

      const outPath = resolve(ROOT, t.out);
      writeFileSync(outPath, pdf);
      console.log('wrote', t.out, '·', pdf.length, 'bytes');
      await page.close();
    }

    await browser.close();
  } finally {
    server.kill();
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
