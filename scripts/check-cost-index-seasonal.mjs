#!/usr/bin/env node
/**
 * check-cost-index-seasonal.mjs — enforcing gate for the rendered "typical for
 * this month" seasonal bands on the cost-index ingredient pages.
 *
 * The bands (scripts/build-cost-index-pages.mjs → seasonalBand) state a
 * multi-year seasonal norm — median + p25–p75 for the reading's calendar month.
 * The methodology's stated bar is that a month earns a "typical" figure ONLY
 * once observed across >=2 distinct calendar years. The fabrication regex gate
 * cannot catch a plausible-but-wrong statistic, so this gate is the deterministic
 * safety net the auditor asked for: it re-derives every rendered band from
 * data/seasonality.json and FAILS on any drift or any band that should not exist.
 *
 * Each band carries machine-readable attributes:
 *   data-season-month / -med / -lo / -hi / -years / -n
 * which must match seasonality.json exactly, on a `ready` ingredient, with the
 * month's `years` >= 2.
 *
 * An absence of bands is valid (the calendar-sensitive pages are committed
 * reverted-to-source and regenerated by the refresh workflow; the gate then has
 * nothing to check until the next render). It only ever fails on a WRONG band.
 *
 *   node scripts/check-cost-index-seasonal.mjs            # CI gate
 *   node scripts/check-cost-index-seasonal.mjs --self-test
 */
import { readFileSync, readdirSync, existsSync, statSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

// Load data/seasonality.json into a { key -> entry } map. Shape is an array of
// per-ingredient entries each carrying `.key`, `.ready`, `.months[MM]`.
export function loadSeasonMap() {
  const raw = JSON.parse(readFileSync(path.join(repoRoot, 'data/seasonality.json'), 'utf8'));
  const arr = Array.isArray(raw) ? raw : (raw.ingredients || []);
  const map = {};
  for (const e of arr) { if (e && e.key) map[e.key] = e; }
  return map;
}

// Parse every <div class="ci-season" …> band out of one page's HTML into a
// record carrying the slug + the asserted figures. Pure string work.
export function parseBands(html, slug, file) {
  const out = [];
  const re = /<div class="ci-season"([^>]*)>/g;
  let m;
  while ((m = re.exec(html))) {
    const attrs = m[1];
    const get = (name) => { const a = attrs.match(new RegExp(`data-season-${name}="([^"]*)"`)); return a ? a[1] : null; };
    out.push({
      slug, file,
      month: parseInt(get('month'), 10),
      med: parseInt(get('med'), 10),
      lo: parseInt(get('lo'), 10),
      hi: parseInt(get('hi'), 10),
      years: parseInt(get('years'), 10),
      n: parseInt(get('n'), 10),
    });
  }
  return out;
}

// The honesty contract, pure so the self-test can exercise it with synthetic
// data. Returns an array of human-readable error strings (empty = clean).
export function validate(bands, seasonMap) {
  const errors = [];
  for (const b of bands) {
    const where = `${b.file} [${b.slug}]`;
    const e = seasonMap[b.slug];
    if (!e) { errors.push(`${where}: seasonal band rendered but '${b.slug}' is absent from seasonality.json`); continue; }
    if (!e.ready) { errors.push(`${where}: seasonal band rendered but '${b.slug}' is not ready (ready=false)`); continue; }
    const mm = String(b.month).padStart(2, '0');
    const md = e.months && e.months[mm];
    if (!md) { errors.push(`${where}: no seasonality data for month ${mm}`); continue; }
    if (!(md.years >= 2)) { errors.push(`${where}: month ${mm} has only ${md.years} distinct year(s) — below the >=2 bar; this band must not render`); continue; }
    if (md.medianCents !== b.med) errors.push(`${where} month ${mm}: median ${b.med} != seasonality ${md.medianCents}`);
    if (md.p25Cents !== b.lo) errors.push(`${where} month ${mm}: p25 ${b.lo} != seasonality ${md.p25Cents}`);
    if (md.p75Cents !== b.hi) errors.push(`${where} month ${mm}: p75 ${b.hi} != seasonality ${md.p75Cents}`);
    if (md.years !== b.years) errors.push(`${where} month ${mm}: years ${b.years} != seasonality ${md.years}`);
    if (md.n !== b.n) errors.push(`${where} month ${mm}: n ${b.n} != seasonality ${md.n}`);
  }
  return errors;
}

// Collect cost-index/<slug>/index.html + es/cost-index/<slug>/index.html.
function collectPages() {
  const pages = [];
  for (const prefix of ['cost-index', path.join('es', 'cost-index')]) {
    const dir = path.join(repoRoot, prefix);
    if (!existsSync(dir)) continue;
    for (const name of readdirSync(dir)) {
      const idx = path.join(dir, name, 'index.html');
      if (existsSync(idx) && statSync(idx).isFile()) {
        pages.push({ slug: name, file: path.join(prefix, name, 'index.html'), abs: idx });
      }
    }
  }
  return pages;
}

function run() {
  if (process.argv.includes('--self-test')) return selfTest();
  let seasonMap;
  try { seasonMap = loadSeasonMap(); }
  catch (e) { console.error('cost-index seasonal: cannot read data/seasonality.json —', e.message); process.exit(1); }
  const pages = collectPages();
  let bands = [];
  for (const p of pages) {
    const html = readFileSync(p.abs, 'utf8');
    if (html.indexOf('class="ci-season"') === -1) continue;
    bands = bands.concat(parseBands(html, p.slug, p.file));
  }
  const errors = validate(bands, seasonMap);
  if (errors.length) {
    for (const e of errors) console.error('  ✗ ' + e);
    console.error(`cost-index seasonal: ${errors.length} problem(s) across ${bands.length} rendered band(s).`);
    process.exit(1);
  }
  console.log(`cost-index seasonal: OK — ${bands.length} rendered band(s) reconcile to seasonality.json${bands.length === 0 ? ' (none rendered — pages awaiting refresh-workflow regen)' : ''}.`);
  process.exit(0);
}

function selfTest() {
  const cases = [];
  const ok = (name, got, want) => cases.push({ name, pass: got === want, got, want });
  const map = {
    broccoli: { key: 'broccoli', ready: true, months: { '06': { medianCents: 2963, p25Cents: 2644, p75Cents: 3335, n: 14, years: 4 } } },
    onion: { key: 'onion', ready: true, months: { '06': { medianCents: 1200, p25Cents: 1000, p75Cents: 1400, n: 6, years: 1 } } },
    kale: { key: 'kale', ready: false, months: { '06': { medianCents: 900, p25Cents: 800, p75Cents: 1000, n: 8, years: 3 } } },
  };
  const goodBand = { slug: 'broccoli', file: 'cost-index/broccoli/index.html', month: 6, med: 2963, lo: 2644, hi: 3335, years: 4, n: 14 };

  ok('valid band → 0 errors', validate([goodBand], map).length, 0);
  ok('no bands → 0 errors', validate([], map).length, 0);
  ok('median drift → error', validate([{ ...goodBand, med: 2900 }], map).length, 1);
  ok('p25 drift → error', validate([{ ...goodBand, lo: 2600 }], map).length, 1);
  ok('n drift → error', validate([{ ...goodBand, n: 13 }], map).length, 1);
  ok('unknown ingredient → error', validate([{ ...goodBand, slug: 'unobtanium' }], map).length, 1);
  ok('not-ready ingredient → error', validate([{ ...goodBand, slug: 'kale', med: 900, lo: 800, hi: 1000, years: 3, n: 8 }], map).length, 1);
  ok('only 1 distinct year → error', validate([{ slug: 'onion', file: 'f', month: 6, med: 1200, lo: 1000, hi: 1400, years: 1, n: 6 }], map).length, 1);
  // parseBands round-trips the attributes it will see in real HTML.
  const html = '<div class="ci-season" data-season-month="6" data-season-med="2963" data-season-lo="2644" data-season-hi="3335" data-season-years="4" data-season-n="14"><p>x</p></div>';
  const parsed = parseBands(html, 'broccoli', 'f');
  ok('parseBands count', parsed.length, 1);
  ok('parseBands median', parsed[0] && parsed[0].med, 2963);
  ok('parseBands valid → 0 errors', validate(parsed, map).length, 0);

  const failed = cases.filter((c) => !c.pass);
  for (const c of failed) console.error(`  ✗ ${c.name}: got ${JSON.stringify(c.got)}, want ${JSON.stringify(c.want)}`);
  console.log(`cost-index seasonal self-test: ${cases.length - failed.length}/${cases.length} passed.`);
  process.exit(failed.length ? 1 : 0);
}

if (path.resolve(process.argv[1] || '') === fileURLToPath(import.meta.url)) run();
