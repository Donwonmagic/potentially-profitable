#!/usr/bin/env node
/**
 * build-dark-mode.mjs — generate the dark-mode contrast-completion block
 * inside assets/site.css from one source-of-truth rule list.
 *
 * Why this exists
 * ---------------
 * The Phase 5 + Phase 9 dark theme only re-pigmented the body and a small
 * "homepage-safe" set of surfaces. The rest of the chrome and ~all card /
 * container families kept their LIGHT-theme tokens (var(--cream)/(--white)
 * backgrounds, var(--ink)/(--teal) text) against the near-black dark body —
 * so in OS dark mode the nav wordmark, the outlined buttons, the FAQ rows,
 * the eyebrows, and most cards rendered with little or no contrast (the
 * 2026-05-30 report). The cream-tuned accent (--teal #2A50C8) is itself too
 * dark to clear AA on near-black, so accents need a lighter blue.
 *
 * Rather than hand-maintain two parallel copies of ~80 rules (the
 * `@media (prefers-color-scheme: dark)` path AND the explicit
 * `[data-theme="dark"]` override path), this script holds ONE list and emits
 * both. Every color pair below is verified ≥ WCAG AA by check-dark-contrast.mjs
 * (text 4.5:1, large text / UI borders 3:1) against the dark surface ramp:
 *   bg #16181D · surface-1 #1B1E24 · surface-2 #23272F
 *   text #F1EDE5 (15.2:1) · text-soft #B8B3A8 (8.5:1) · accent #7AA7FF (7.4:1)
 *   border-strong #6B7280 (3.7:1; chevrons/outlines)
 *
 * The block is delimited in assets/site.css by:
 *   GEN:dark-mode:start … GEN:dark-mode:end
 * The @shell:core marker on the opening line makes build-css-shells.mjs fold
 * it into the render-blocking site-core.css, so there is NO light→dark flash
 * on first paint.
 *
 * Run:        node scripts/build-dark-mode.mjs           # rewrite the block
 * Check:      node scripts/build-dark-mode.mjs --check    # exit 1 if stale
 * Pipeline:   before build-css-shells.mjs (so the shell picks up the change).
 */

