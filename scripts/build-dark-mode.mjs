const fmtTokens = (obj) =>
  Object.entries(obj)
    .map(([k, v]) => `  ${k}: ${v};`)
    .join("\n");

const selJoin = (prefix, selectors) =>
  selectors.map((s) => prefix + s).join(",\n  ");

// Emit the exception rule rows (comment rows are single-string arrays).
const emitExceptions = (prefix) =>
  EXCEPTIONS.map((entry) => {
    if (!Array.isArray(entry[0])) return "  " + entry[0];
    const [selectors, decls] = entry;
    return `  ${selJoin(prefix, selectors)}{${decls}}`;
  }).join("\n");

function darkPayload(rootPrefix) {
  // rootPrefix is the activation root WITHOUT a trailing space, e.g.
  // ':root:not([data-theme="light"])' or ':root[data-theme="dark"]'.
  const sp = rootPrefix + " ";
  return [
    `${rootPrefix}{`,
    "  /* Flip the base palette — every surface + its text invert together. */",
    fmtTokens(DARK),
    "}",
    "",
    "  /* Inverted-by-design surfaces: restore light-mode tokens so the surface",
    "     and all its descendants render as in light mode (children inherit). */",
    `  ${selJoin(sp, INVERTED)}{`,
    fmtTokens(LIGHT)
      .split("\n")
      .map((l) => "  " + l)
      .join("\n"),
    "  }",
    "",
    emitExceptions(sp),
  ].join("\n");
}

function buildBlock() {
  const osPayload = darkPayload(':root:not([data-theme="light"])')
    .split("\n")
    .map((l) => (l.length ? "  " + l : l))
    .join("\n");

  const media = "@media (prefers-color-scheme: dark){\n" + osPayload + "\n}";
  const explicit = darkPayload(':root[data-theme="dark"]');

  return [
    START,
    "/* TOKEN-FLIP dark theme (see scripts/build-dark-mode.mjs). The base palette",
    "   is remapped at the dark root so every surface and its text flip together;",
    "   inverted-by-design surfaces scope-restore the light tokens. Two activation",
    "   paths: OS preference (gated so the explicit Light toggle wins) + the",
    "   [data-theme=\"dark\"] toggle. AA-verified by check-dark-contrast.mjs. */",
    "",
    "/* Base (light) values for de-inlined homepage notes. */",
    ".hp-smaller-note{color:var(--ink-soft)}",
    ".hp-smaller-note-link{color:var(--teal)}",
    "",
    "/* ===== OS preference path ===== */",
    media,
    "",
    "/* ===== Explicit [data-theme=\"dark\"] path ===== */",
    explicit,
    END,
  ].join("\n");
}

function main() {
  const check = process.argv.includes("--check");
  const css = fs.readFileSync(SITE_CSS, "utf8");
  const s = css.indexOf(START);
  const e = css.indexOf(END);
  if (s === -1 || e === -1) {
    console.error(`build-dark-mode: markers not found in assets/site.css (${START} … ${END}). Add them where the block should live.`);
    process.exit(1);
  }
  const block = buildBlock();
  const next = css.slice(0, s) + block + css.slice(e + END.length);
  if (next === css) {
    console.log("build-dark-mode: block already up to date.");
    return;
  }
  if (check) {
    console.error("build-dark-mode: assets/site.css dark-mode block is STALE. Run: node scripts/build-dark-mode.mjs");
    process.exit(1);
  }
  fs.writeFileSync(SITE_CSS, next);
  console.log(`build-dark-mode: regenerated the token-flip dark block (${Object.keys(DARK).length} tokens, ${INVERTED.length} inverted surfaces, 2 activation paths).`);
}

main();
