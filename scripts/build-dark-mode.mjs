function buildBlock() {
  const roots = [
    ':root:not([data-theme="light"]) ', // OS preference path
  ];
  const explicitRoot = ':root[data-theme="dark"] ';

  // Emit the @media path and the [data-theme] path from the same list.
  const emit = (prefix) =>
    RULES.map((entry) => {
      if (entry.length === 1) return "  " + entry[0]; // comment row
      const [selectors, decls] = entry;
      const sel = selectors.map((s) => prefix + s).join(",\n  ");
      return `  ${sel}{${decls}}`;
    }).join("\n");

  const media =
    "@media (prefers-color-scheme: dark){\n" + emit(roots[0]) + "\n}";
  const explicit = emit(explicitRoot)
    .split("\n")
    .map((l) => (l.startsWith("  /*") ? l.trimStart() : l.trimStart()))
    .join("\n");

  return [
    START,
    "/* One source list, two activation paths (OS preference + explicit",
    "   [data-theme=\"dark\"] toggle). Regenerate with scripts/build-dark-mode.mjs.",
    "   Backgrounds and text are flipped together so no surface is ever left",
    "   light-on-light; every pair clears WCAG AA (see check-dark-contrast.mjs). */",
    "",
    "/* Base (light) values for de-inlined homepage notes. */",
    ".hp-smaller-note{color:var(--ink-soft)}",
    ".hp-smaller-note-link{color:var(--teal)}",
    "",
    media,
    "",
    "/* Explicit-override twin. */",
    explicit,
    END,
  ].join("\n");
}

function main() {
  const check = process.argv.includes("--check");
  const css = fs.readFileSync(SITE_CSS, "utf8");
  const s = css.indexOf(START);
  const e = css.indexOf(END);
  if (s === -1 || e === -1) {
    console.error(`build-dark-mode: markers not found in assets/site.css (${START} … ${END}). Add them where the block should live.`);
    process.exit(1);
  }
  const block = buildBlock();
  const next = css.slice(0, s) + block + css.slice(e + END.length);
  if (next === css) {
    console.log("build-dark-mode: block already up to date.");
    return;
  }
  if (check) {
    console.error("build-dark-mode: assets/site.css dark-mode block is STALE. Run: node scripts/build-dark-mode.mjs");
    process.exit(1);
  }
  fs.writeFileSync(SITE_CSS, next);
  const ruleCount = RULES.filter((r) => r.length === 2).length;
  console.log(`build-dark-mode: regenerated the dark-mode block (${ruleCount} rule groups × 2 activation paths).`);
}

main();
