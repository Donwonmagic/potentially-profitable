#!/usr/bin/env node
/**
 * build-dark-mode.mjs — generate the dark-mode block inside assets/site.css.
 *
 * Architecture (2026-05-30 rewrite): TOKEN FLIP, not an allowlist.
 * ----------------------------------------------------------------
 * The previous dark theme was a hand-maintained allowlist: it flipped a
 * curated set of surfaces to dark and a curated set of text to light. Any
 * surface NOT on the list kept its light value, which guaranteed mismatches —
 * light card + light heading (invisible), or dark card + dark caption
 * (invisible). The live site showed exactly that (forms with invisible labels,
 * library cards with invisible titles, faint headings). An allowlist over a
 * ~9000-line stylesheet can never be complete.
 *
 * This generator instead REMAPS THE BASE PALETTE TOKENS at the dark root, so
 * every `var(--cream)` surface and every `var(--ink)` text flips TOGETHER, by
 * construction — no surface can be left light-on-light or dark-on-dark, because
 * a surface and its text resolve from the same flipped tokens.
 *
 *   light value            dark value
 *   --cream   #F6F7F8   →  #16181D   (page background)
 *   --white   #FFFFFF   →  #1B1E24   (raised cards)
 *   --cream-2 #EDEEF1   →  #21262E   (inset fills)
 *   --ink     #16181D   →  #F1EDE5   (primary text)        15.2:1
 *   --ink-soft#4A4F59   →  #BBB6AB   (soft text)            ~9:1
 *   --stone   #6B7280   →  #9CA3AE   (muted)                ~6.5:1
 *   --teal    #2A50C8   →  #7AA7FF   (accent text + links)  7.4:1
 *   --line    #E3E5E9   →  #2C3038   (hairlines)
 *
 * The base tokens are OVERLOADED, which is why a naive flip is unsafe and the
 * original author avoided it: --ink is text (214×) AND a dark-by-design
 * background (27×); --cream is a light surface AND light text on dark surfaces
 * (75×). We resolve the overload two ways:
 *
 *  1. CORRELATED PAIRS self-resolve. A dark button `{background:var(--ink);
 *     color:var(--cream)}` flips to `{light pill; dark text}` — the correct
 *     dark-mode primary. No special handling needed.
 *
 *  2. INVERTED-BY-DESIGN surfaces (footer, .process/.final, the muntin compare
 *     card, the Listen dock, toasts) are "always the inverse" — dark in light
 *     mode, and they should STAY dark in dark mode. For these we SCOPE-RESTORE
 *     the tokens to their light values on the surface itself, so the surface
 *     and ALL its descendants render exactly as in light mode (children inherit
 *     the restored tokens — no per-child enumeration). One rule per surface.
 *
 * A short EXCEPTIONS list covers values a token swap can't reach: hardcoded
 * light hex surfaces (won't flip), hardcoded status greens/reds (too dark on
 * dark), and the hero gradient-text (`-webkit-text-fill-color` overrides
 * `color`).
 *
 * Emitted twice: the `@media (prefers-color-scheme: dark)` path (gated by
 * :root:not([data-theme="light"]) so the explicit Light toggle always wins) and
 * the explicit `:root[data-theme="dark"]` path.
 *
 * The block is delimited in assets/site.css by GEN:dark-mode:start … :end. The
 * @shell:core marker on the opening line folds it into the render-blocking
 * site-core.css (no light→dark flash on first paint).
 *
 * Run:    node scripts/build-dark-mode.mjs            # rewrite the block
 * Check:  node scripts/build-dark-mode.mjs --check    # exit 1 if stale
 * Pipeline: before build-css-shells.mjs.
 */

