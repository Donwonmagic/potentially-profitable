#!/usr/bin/env node
// Cards QA — first-impression-bar verification across all five Cards.
// Run via: `node scripts/test-cards-qa.mjs`
//
// The Plate Cost Calculator plan (§3a) raised the bar on every signature
// PNG export to "extraordinary first-impression quality" because every
// download is potentially someone's first encounter with the Muntin
// name. This file enforces the load-bearing pieces of that bar that can
// be verified statically + via the dual-export Node hook each renderer
// module already exposes:
//
//   - Module API parity: every renderer exports awaitFonts(),
//     canvasToPngBlob(), DEFAULT_STRINGS_EN, DEFAULT_STRINGS_ES, and
//     its render entry-point(s).
//
//   - awaitFonts() resolves cleanly under Node (where document.fonts
//     does not exist) so pages that await it never hang.
//
//   - Unified footer treatment: every footer string follows the
//     pattern "Generated by Muntin · [Tool Name] · muntin.digital"
//     (and Spanish equivalent), so a forwarded Card carries the
//     studio attribution legibly regardless of which tool generated
//     it.
//
//   - Privacy invariant: no remote network calls in any renderer
//     source (no fetch, XMLHttpRequest, dynamic import, or remote
//     URL outside the inline muntin.digital credit strings).
//
//   - Margin discipline: footer text uses the 48 px keep-out from
//     each canvas edge that the bar requires.
//
// Exits non-zero on failure.

import { createRequire } from 'node:module';
import { readFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');

let failures = 0;
function assert(label, cond, detail) {
  console.log((cond ? 'PASS' : 'FAIL') + '  ' + label +
              (cond ? '' : (detail ? '  (' + detail + ')' : '')));
  if (!cond) failures++;
}

// ------------------------------------------------------------
// Renderer registry — every Card surface in the toolkit. The
// "renderEntries" array names every public render-function that
// must be present; "footerKeys" names every (left, right) pair
// the source contains for footer treatment.
// ------------------------------------------------------------
const RENDERERS = [
  {
    label:        'Brand Suite — Muntin Pane',
    modulePath:   'tools/brand-suite/pane-render.js',
    moduleApi:    'BSPane',
    renderEntries: ['renderMuntinPane'],
    enToolName:   'Brand Suite',
    esToolName:   'Suite de Marca'
  },
  {
    label:        'Menu Engineering — Menu Card',
    modulePath:   'tools/menu-engineering/card-render.js',
    moduleApi:    'MECard',
    renderEntries: ['renderMenuCard'],
    enToolName:   'Menu Engineering Matrix',
    esToolName:   'Matriz de Ingeniería de Menú'
  },
  {
    label:        'Menu Copy — Copy Card',
    modulePath:   'tools/menu-copy/card-render.js',
    moduleApi:    'MCCard',
    renderEntries: ['renderCopyCards'],
    enToolName:   'Menu Copy Inspector',
    esToolName:   'Inspector de Copy de Menú'
  },
  {
    label:        'Open Hours — Sign + Card',
    modulePath:   'tools/open-hours/sign-render.js',
    moduleApi:    'OHSign',
    renderEntries: ['renderStorefrontSign', 'renderOpenHoursCard'],
    enToolName:   'Open Hours',
    esToolName:   'Horario Abierto'
  },
  {
    label:        'Plate Cost — Plate Card',
    modulePath:   'tools/plate-cost/card-render.js',
    moduleApi:    'PCCard',
    renderEntries: ['renderPlateCard'],
    enToolName:   'Plate Cost Calculator',
    esToolName:   'Calculadora de Costo del Plato'
  },
  {
    label:        'Photo Brief — Photo Brief + Brand Photo Card',
    modulePath:   'tools/photo-brief/card-render.js',
    moduleApi:    'PBCard',
    renderEntries: ['renderPhotoBrief', 'renderBrandPhotoCard'],
    enToolName:   'Photo Brief Builder',
    esToolName:   'Constructor de Brief de Fotos'
  },
  {
    label:        'Brand Suite — Palette Sheet',
    modulePath:   'tools/brand-suite/palette-sheet-render.js',
    moduleApi:    'BSPaletteSheet',
    renderEntries: ['renderPaletteSheet'],
    enToolName:   'Brand Suite',
    esToolName:   'Suite de Marca'
  }
];

// ------------------------------------------------------------
// 1. Module API parity. Every Card module exposes the same set of
// load-bearing symbols. Drift here means a page calling Module.x
// works against one tool but throws against another.
// ------------------------------------------------------------
const loaded = RENDERERS.map(r => ({ ...r, mod: require(resolve(ROOT, r.modulePath)) }));

for (const r of loaded) {
  for (const fn of ['awaitFonts', 'canvasToPngBlob', 'DEFAULT_STRINGS_EN', 'DEFAULT_STRINGS_ES']) {
    const ok = r.mod[fn] !== undefined;
    assert(`${r.label}: exports ${fn}`, ok);
  }
  for (const fn of r.renderEntries) {
    const ok = typeof r.mod[fn] === 'function';
    assert(`${r.label}: exports ${fn}() function`, ok);
  }
}

// ------------------------------------------------------------
// 2. awaitFonts() under Node: resolves immediately when document.fonts
// is unavailable. A page calling `await Module.awaitFonts()` must never
// hang in any environment.
// ------------------------------------------------------------
for (const r of loaded) {
  if (typeof r.mod.awaitFonts !== 'function') continue;
  const result = r.mod.awaitFonts();
  assert(`${r.label}: awaitFonts() returns a Promise`, result && typeof result.then === 'function');
  // Race against an immediate resolution to confirm it doesn't hang.
  let resolved = false;
  await Promise.race([
    result.then(() => { resolved = true; }),
    new Promise(res => setTimeout(res, 50))
  ]);
  assert(`${r.label}: awaitFonts() resolves under Node within 50 ms`, resolved);
}

// ------------------------------------------------------------
// 3. Unified footer treatment. Every footer string follows the
// pattern "Generated by Muntin · [Tool Name] · muntin.digital" (EN)
// and "Generado por Muntin · [Tool Name] · muntin.digital" (ES).
// We extract the footer string from each renderer's DEFAULT_STRINGS
// (which varies by module — left/right vs cardFooterLeft/Right vs
// signFooterCredit) and assert the canonical shape.
// ------------------------------------------------------------

// Pull every footer-bearing string from a default-strings object.
// The four renderers use slightly different string keys; this is
// the canonical list.
const FOOTER_STRING_KEYS = [
  ['footer', 'left'],         // Pane: { footer: { left, right } }
  ['footerLeft'],             // Menu Card / Copy Card: top-level footerLeft
  ['cardFooterLeft'],         // Open Hours Card
  ['signFooterCredit']        // Open Hours Sign (centered tracked credit)
];
function pickFooterStrings(strings) {
  const out = [];
  for (const path of FOOTER_STRING_KEYS) {
    let v = strings;
    for (const key of path) v = v && v[key];
    if (typeof v === 'string') out.push({ key: path.join('.'), value: v });
  }
  return out;
}

const enExpected = /^Generated by Muntin · .+ · muntin\.digital$/;
const esExpected = /^Generado por Muntin · .+ · muntin\.digital$/;

for (const r of loaded) {
  const enFooters = pickFooterStrings(r.mod.DEFAULT_STRINGS_EN);
  const esFooters = pickFooterStrings(r.mod.DEFAULT_STRINGS_ES);
  assert(`${r.label}: at least one EN footer string present`, enFooters.length > 0);
  assert(`${r.label}: at least one ES footer string present`, esFooters.length > 0);
  for (const f of enFooters) {
    const ok = enExpected.test(f.value);
    assert(`${r.label}: EN ${f.key} matches "Generated by Muntin · ... · muntin.digital"`, ok, f.value);
  }
  for (const f of esFooters) {
    const ok = esExpected.test(f.value);
    assert(`${r.label}: ES ${f.key} matches "Generado por Muntin · ... · muntin.digital"`, ok, f.value);
  }
  // Each footer string mentions its tool name verbatim.
  for (const f of enFooters) {
    assert(`${r.label}: EN ${f.key} names the tool "${r.enToolName}"`,
           f.value.includes(r.enToolName));
  }
  for (const f of esFooters) {
    assert(`${r.label}: ES ${f.key} names the tool "${r.esToolName}"`,
           f.value.includes(r.esToolName));
  }
}

// ------------------------------------------------------------
// 4. Privacy invariant — no remote network calls in renderer source.
// Static analysis only: searches the source for fetch(, XMLHttpRequest,
// dynamic import(, or any http(s) URL that isn't an inline credit
// string targeting muntin.digital.
// ------------------------------------------------------------
for (const r of loaded) {
  const src = readFileSync(resolve(ROOT, r.modulePath), 'utf8');
  // Ban runtime network primitives.
  assert(`${r.label}: no fetch( in source`, !/\bfetch\s*\(/.test(src));
  assert(`${r.label}: no XMLHttpRequest in source`, !/XMLHttpRequest/.test(src));
  // Dynamic import would let a renderer pull in remote ESM. Static
  // require/import at the top is fine; runtime import() is the leak.
  assert(`${r.label}: no dynamic import() in source`, !/\bimport\s*\(/.test(src));
  // No XHR-equivalent. <img src="https://..."> in canvas would taint.
  // The only http/https mentions allowed are the muntin.digital credit
  // string in DEFAULT_STRINGS, which appears as a plain literal.
  const remoteUrls = (src.match(/https?:\/\/[^\s"'`)]+/g) || [])
    .filter(u => !/^https?:\/\/(?:www\.)?muntin\.digital/i.test(u));
  assert(`${r.label}: no non-muntin.digital remote URLs in source`,
         remoteUrls.length === 0,
         remoteUrls.slice(0, 3).join(', '));
}

// ------------------------------------------------------------
// 5. Margin discipline — footer text uses 48 px keep-out from each
// canvas edge. The renderers all encode this as a numeric literal
// in the drawFooter call (`24` was the prior shipped value; the bar
// requires 48). Assert no `(strings.footerLeft, 24,` or similar
// leftover-24px footer-text positions remain.
// ------------------------------------------------------------
for (const r of loaded) {
  const src = readFileSync(resolve(ROOT, r.modulePath), 'utf8');
  // Look for any footer drawText call that uses a 24px x-offset.
  // Canonical patterns:
  //   ctx.fillText(footerStrings.left, 24, ...)
  //   ctx.fillText(strings.footerLeft, 24, ...)
  //   ctx.fillText(strings.cardFooterLeft, 24, ...)
  const offending = (src.match(/fillText\([^)]*footer[^)]*,\s*24\s*,/gi) || [])
    .concat(src.match(/fillText\([^)]*Footer[^)]*,\s*W\s*-\s*24\s*,/gi) || []);
  assert(`${r.label}: no 24px footer-text offsets remain (need 48 px keep-out)`,
         offending.length === 0,
         offending.slice(0, 2).join(' | '));
}

// ------------------------------------------------------------
// 6. Recessive-credit opacity — every renderer's footer credit paints
// at 60% opacity (cream-on-ink for the standard footer band; ink-on-
// cream for the Sign's centered tracked credit). The bar requires the
// credit be calm, not loud. We assert each source contains an rgba
// string at 0.6 alpha used in a footer context.
// ------------------------------------------------------------
const RECESSIVE_RGBA = /rgba\(\s*(?:250\s*,\s*247\s*,\s*242|20\s*,\s*22\s*,\s*26)\s*,\s*0\.6\s*\)/i;
for (const r of loaded) {
  const src = readFileSync(resolve(ROOT, r.modulePath), 'utf8');
  assert(`${r.label}: footer paints at 60% opacity (recessive credit)`,
         RECESSIVE_RGBA.test(src));
}

// ------------------------------------------------------------
// 7. Cross-renderer consistency — all four modules ship the same
// footer-pattern shape. If the prefix or suffix drift, the Cards
// stop reading as one studio's work.
// ------------------------------------------------------------
const allEnFooters = loaded.flatMap(r => pickFooterStrings(r.mod.DEFAULT_STRINGS_EN).map(f => f.value));
const allEsFooters = loaded.flatMap(r => pickFooterStrings(r.mod.DEFAULT_STRINGS_ES).map(f => f.value));
assert('every EN footer starts with "Generated by Muntin · "',
       allEnFooters.every(s => s.startsWith('Generated by Muntin · ')));
assert('every ES footer starts with "Generado por Muntin · "',
       allEsFooters.every(s => s.startsWith('Generado por Muntin · ')));
assert('every EN footer ends with " · muntin.digital"',
       allEnFooters.every(s => s.endsWith(' · muntin.digital')));
assert('every ES footer ends with " · muntin.digital"',
       allEsFooters.every(s => s.endsWith(' · muntin.digital')));

// ------------------------------------------------------------
console.log('\n' + (failures === 0
  ? '✓ all card-QA assertions pass'
  : '✗ ' + failures + ' card-QA assertion(s) failed'));
process.exit(failures === 0 ? 0 : 1);
