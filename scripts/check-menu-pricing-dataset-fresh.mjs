#!/usr/bin/env node
/**
 * check-menu-pricing-dataset-fresh.mjs — keep the published menu-pricing dataset honest about
 * being current, given that the generator behind it is not in any build chain.
 *
 * WHY THIS EXISTS
 * `researchTargets()` in scripts/lib/cost-research.mjs emits six artifacts — the EN/ES
 * menu-pricing playbook, the EN/ES study, and cost-index/menu-pricing.{json,csv}. **Nothing
 * imports researchTargets().** Its own file header asserted the opposite until 2026-07-31
 * ("Consumed by build-cost-index-pages.mjs"), which is very likely why the gap survived: the
 * file vouched for its own wiring.
 *
 * So those six published surfaces are FROZEN OUTPUTS, not live ones. Audited 2026-07-31: they
 * are not currently stale — band_pct and posture match data/cost-lockfloat.json on all 100 rows.
 * The hazard is that nothing would say so once the source data moves. A frozen dataset and a
 * current one are byte-identical right up to the moment they are not, which is exactly the
 * silent-zero shape of ADR-023: absence of a signal that the instrument stopped.
 *
 * This gate recomputes the two DATA artifacts from the live sources and fails on drift. It does
 * NOT gate the four HTML surfaces — re-wiring the generator would regenerate live published
 * pages, and that is a founder call, not a cleanup. Scope is stated rather than silently narrow.
 *
 *   node scripts/check-menu-pricing-dataset-fresh.mjs             # CI
 *   node scripts/check-menu-pricing-dataset-fresh.mjs --write     # regenerate the two artifacts
 *   node scripts/check-menu-pricing-dataset-fresh.mjs --self-test
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { pricingDataset } from './lib/cost-research.mjs'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const ARTIFACTS = [
  { rel: 'cost-index/menu-pricing.json', key: 'json' },
  { rel: 'cost-index/menu-pricing.csv', key: 'csv' },
]

/** Compare committed bytes to freshly generated bytes. Returns one row per artifact. */
export function compare (generated, readFile) {
  return ARTIFACTS.map(({ rel, key }) => {
    const committed = readFile(rel)
    return { rel, present: committed != null, drifted: committed != null && committed !== generated[key] }
  })
}

/** First differing line, for an actionable failure message rather than "they differ". */
export function firstDiff (a, b) {
  const A = String(a).split('\n')
  const B = String(b).split('\n')
  for (let i = 0; i < Math.max(A.length, B.length); i++) {
    if (A[i] !== B[i]) return { line: i + 1, committed: A[i] ?? '(missing)', generated: B[i] ?? '(missing)' }
  }
  return null
}

// ---------------------------------------------------------------------------
function selfTest () {
  let n = 0
  const ok = (c, m) => { n++; if (!c) { console.error(`  FAIL: ${m}`); process.exitCode = 1 } }

  ok(firstDiff('a\nb', 'a\nb') === null, 'identical content has no diff')
  ok(firstDiff('a\nb', 'a\nc').line === 2, 'reports the 1-indexed first differing line')
  ok(firstDiff('a', 'a\nb').line === 2, 'a longer generated side is a diff, not a crash')
  ok(firstDiff('a\nb', 'a').generated === '(missing)', 'names the missing side explicitly')

  const gen = { json: 'J', csv: 'C' }
  const all = compare(gen, (rel) => (rel.endsWith('.json') ? 'J' : 'C'))
  ok(all.every((r) => !r.drifted), 'matching artifacts do not drift')
  ok(all.every((r) => r.present), 'both artifacts reported present')
  const one = compare(gen, (rel) => (rel.endsWith('.json') ? 'STALE' : 'C'))
  ok(one.filter((r) => r.drifted).length === 1, 'only the drifted artifact is flagged')
  ok(one.find((r) => r.rel.endsWith('.json')).drifted === true, 'the json drift is the one caught')
  const none = compare(gen, () => null)
  ok(none.every((r) => !r.present), 'a missing artifact is reported absent')
  ok(none.every((r) => !r.drifted), 'a missing artifact is absent, NOT drifted — different failures')

  console.log(`self-test: ${n} assertions${process.exitCode ? ' — FAILURES ABOVE' : ' passed'}`)
}

// ---------------------------------------------------------------------------
const argv = process.argv.slice(2)
if (argv.includes('--self-test')) {
  selfTest()
} else {
  const ds = pricingDataset(ROOT)
  const readFile = (rel) => {
    const p = resolve(ROOT, rel)
    return existsSync(p) ? readFileSync(p, 'utf8') : null
  }

  if (argv.includes('--write')) {
    for (const { rel, key } of ARTIFACTS) writeFileSync(resolve(ROOT, rel), ds[key])
    console.log(`menu-pricing dataset: regenerated ${ARTIFACTS.map((a) => a.rel).join(' + ')}.`)
    process.exit(0)
  }

  const rows = compare(ds, readFile)
  const bad = rows.filter((r) => !r.present || r.drifted)
  for (const r of rows) {
    if (!r.present) { console.error(`  MISSING: ${r.rel}`); continue }
    if (!r.drifted) continue
    const key = r.rel.endsWith('.json') ? 'json' : 'csv'
    const d = firstDiff(readFile(r.rel), ds[key])
    console.error(`  DRIFT: ${r.rel}${d ? ` — first difference at line ${d.line}` : ''}`)
    if (d) {
      console.error(`    committed:  ${String(d.committed).slice(0, 120)}`)
      console.error(`    generated:  ${String(d.generated).slice(0, 120)}`)
    }
  }
  if (bad.length) {
    console.error('\ncheck-menu-pricing-dataset-fresh: the published dataset no longer matches its source.')
    console.error('  Its generator (researchTargets/pricingDataset) is in NO build chain, so nothing')
    console.error('  regenerates it automatically. Run --write to refresh the two data artifacts.')
    console.error('  NOTE: the four HTML surfaces from the same generator are NOT covered here.')
    process.exit(1)
  }
  console.log(`check-menu-pricing-dataset-fresh: OK — ${ARTIFACTS.length} artifact(s) match the live sources.`)
}
