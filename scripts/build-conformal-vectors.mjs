#!/usr/bin/env node
/**
 * build-conformal-vectors.mjs — GOLDEN VECTORS for the parity-locked conformal band.
 *
 * The certified band lives in two repos (tools/_shared/cost-conformal.js here,
 * packages/cost-alerts/src/cost-conformal.ts in Muntin Ledger). The mirrored test
 * suites pin BEHAVIOUR, but with tolerance bands ("coverage between 0.68 and 0.92"),
 * so a subtle NUMERIC drift between the two ports — a rounding difference, an
 * off-by-one in a window slice — could pass both suites while the numbers silently
 * diverge. This writes an EXACT, byte-for-byte fixture of full conformalNext outputs
 * over a fixed battery of deterministic series. Both repos assert their port
 * reproduces this same file to the last digit, so any numeric divergence is a test
 * failure, not a coincidence.
 *
 *   node scripts/build-conformal-vectors.mjs           # (re)write the fixture (both repos)
 *   node scripts/build-conformal-vectors.mjs --check   # CI: fail if either copy is stale
 *
 * The Ledger copy (packages/cost-alerts/tests/cost-conformal.vectors.json) is written
 * only when that sibling repo is checked out beside this one; in a lone-repo CI its
 * own committed copy stands and this script leaves it untouched.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { conformalNext } = require(path.join(repo, 'tools/_shared/cost-conformal.js'));

const OUT_JSON = path.join(repo, 'tools/_shared/cost-conformal.vectors.json');
// The Ledger port's fixture — same bytes, so the TS suite pins to the identical golden set.
const LEDGER_JSON = path.resolve(repo, '..', 'Muntin-Invoice-Decoder', 'packages/cost-alerts/tests/cost-conformal.vectors.json');

// Deterministic PRNG + walk — copied verbatim from the mirrored test suites so the
// generated series are reproducible without a build clock or Math.random.
function mulberry32(seed) {
  return function () {
    seed |= 0; seed = (seed + 0x6D2B79F5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
function walk(n, seed, step) {
  const rng = mulberry32(seed); const out = [1000];
  for (let i = 1; i < n; i++) out.push(Math.max(1, Math.round(out[i - 1] + step(rng()))));
  return out;
}

// The battery: named series + opts chosen to exercise every branch of conformalNext
// (healthy coverage, under-coverage + calibration, too-short → null-coverage, flat →
// degenerate, asymmetric rockets-and-feathers, a wide-band float, a monthly-thin case).
const CASES = [
  { name: 'symmetric-walk-80', values: walk(400, 7, (r) => (r - 0.5) * 80), opts: { alpha: 0.20, window: 52 } },
  { name: 'symmetric-walk-80-calibrated', values: walk(400, 7, (r) => (r - 0.5) * 80), opts: { alpha: 0.20, window: 52, calibrate: true } },
  { name: 'symmetric-walk-50', values: walk(400, 99, (r) => (r - 0.5) * 80), opts: { alpha: 0.50, window: 52 } },
  { name: 'short-series-null-coverage', values: walk(14, 3, (r) => (r - 0.5) * 40), opts: { alpha: 0.20 } },
  { name: 'rockets-and-feathers', values: walk(300, 21, (r) => (r < 0.5 ? r * 120 : -(r - 0.5) * 20)), opts: { alpha: 0.20, window: 60 } },
  { name: 'occasional-jump-overcover', values: walk(600, 7, (r) => (r < 0.85 ? (r - 0.5) * 6 : (r - 0.5) * 60)), opts: { alpha: 0.20, window: 60, calibrate: true } },
  { name: 'wide-band-float', values: walk(300, 5, (r) => (r - 0.5) * 300), opts: { alpha: 0.20, window: 40 } },
  { name: 'flat-degenerate', values: new Array(120).fill(2200), opts: { alpha: 0.20, window: 52 } },
];

function build() {
  return {
    _doc: 'GOLDEN VECTORS for cost-conformal — exact conformalNext outputs over a fixed deterministic battery. Both the storefront (tools/_shared/cost-conformal.js) and the Muntin Ledger TS port (packages/cost-alerts/src/cost-conformal.ts) must reproduce this file byte-for-byte; a numeric divergence between the two ports is therefore a test failure, not a coincidence. GENERATED by scripts/build-conformal-vectors.mjs — do not hand-edit; regenerate on any intentional math change (in the SAME commit as the ported change, per the parity contract).',
    _version: 1,
    vectors: CASES.map((c) => ({ name: c.name, input: { values: c.values, opts: c.opts }, expect: conformalNext(c.values, c.opts) })),
  };
}

function serialize(o) { return JSON.stringify(o, null, 2) + '\n'; }

function main() {
  const json = serialize(build());

  if (process.argv.includes('--check')) {
    let cur = '';
    try { cur = readFileSync(OUT_JSON, 'utf8'); } catch {}
    if (cur !== json) { console.error('✗ conformal golden vectors are stale — run: node scripts/build-conformal-vectors.mjs'); process.exit(1); }
    // Cross-repo byte-identity: only assertable when the sibling repo is checked out.
    if (existsSync(LEDGER_JSON)) {
      const led = readFileSync(LEDGER_JSON, 'utf8');
      if (led !== json) { console.error('✗ Ledger conformal vectors DIVERGE from the storefront copy — the parity contract is broken. Re-copy: node scripts/build-conformal-vectors.mjs'); process.exit(1); }
      console.log('✓ conformal golden vectors in sync — storefront + Ledger copies byte-identical (' + build().vectors.length + ' vectors).');
    } else {
      console.log('✓ conformal golden vectors in sync (' + build().vectors.length + ' vectors; Ledger repo not checked out — its own committed copy stands).');
    }
    return;
  }

  writeFileSync(OUT_JSON, json);
  let alsoLedger = '';
  if (existsSync(path.dirname(LEDGER_JSON))) { writeFileSync(LEDGER_JSON, json); alsoLedger = ' + Ledger copy'; }
  console.log('Wrote conformal golden vectors — ' + build().vectors.length + ' vectors' + alsoLedger + '.');
}

main();
