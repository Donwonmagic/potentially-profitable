#!/usr/bin/env node
/**
 * build-cost-pressure.mjs — run the deterministic Pressure engine
 * (tools/_shared/cost-pressure.js) over data/pressure-rules.json + observations,
 * writing data/cost-pressure.json: one INFERRED-direction record per ingredient.
 *
 * THE RECORD HAS NO PRICE. It carries direction / confidence / contributors and
 * points AT the measured anchor (its last print date, read from
 * data/cost-index.json) so the overlay can show "as of" honesty. Pressure is
 * only built for ingredients that already ship a measured reading (the anchor) —
 * an overlay with no anchor would be a forecast floating free, which we don't do.
 *
 * Preview vs live:
 *   - observations from data/pressure-observations.demo.json → status 'preview'.
 *   - (P2) live observations from the free fetchers → status 'live'.
 *
 *   node scripts/build-cost-pressure.mjs            # write
 *   node scripts/build-cost-pressure.mjs --dry-run  # print, don't write
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const { assess } = require(path.join(repoRoot, 'tools/_shared/cost-pressure.js'));
const { isShippable } = require(path.join(repoRoot, 'tools/_shared/cost-confidence.js'));
const Accuracy = require(path.join(repoRoot, 'tools/_shared/pressure-accuracy.js'));
const DRY = process.argv.includes('--dry-run');
const rd = (p) => JSON.parse(readFileSync(path.join(repoRoot, p), 'utf8'));

const rules = rd('data/pressure-rules.json');
const obsDoc = rd('data/pressure-observations.demo.json');
const ci = (rd('data/cost-index.json').ingredients) || {};
const defaults = rules.defaults || {};
const status = obsDoc._status || 'preview';

const items = {};
const anchors = {};   // item → last measured-print date (for the Lab's freshness)
const liveObs = {};   // item → { indicatorId: changePct } (the Lab's "live read" base)
let built = 0, skipped = [];
for (const [item, panelIn] of Object.entries(rules.items || {})) {
  const point = (ci[item] && ci[item].points && ci[item].points[0]) || null;
  // No measured anchor (or below the shippable bar) → no overlay; pressure never floats free.
  if (!point || !isShippable(point)) { skipped.push(item + ' (no shippable anchor)'); continue; }
  const obs = obsDoc.observations[item];
  if (!obs) { skipped.push(item + ' (no observations)'); continue; }
  const observations = {};
  for (const [id, changePct] of Object.entries(obs)) observations[id] = { changePct, asOf: obsDoc.asOf };
  const panel = Object.assign({}, defaults, panelIn, { item, rule_version: panelIn.rule_version || rules._version });
  const rec = assess(panel, observations, { anchorPrintDate: point.asOf || null, asOf: obsDoc.asOf, ruleVersion: rules._version });
  items[item] = rec;
  anchors[item] = point.asOf || null;
  liveObs[item] = obs;   // raw { id: changePct } — the live base the Lab resets to
  built++;
}

const out = {
  _doc: 'GENERATED by scripts/build-cost-pressure.mjs from data/pressure-rules.json + observations. INFERRED direction only — no price. Enforced by scripts/check-pressure-honesty.mjs (recompute-and-compare).',
  _version: rules._version,
  status,
  asOf: obsDoc.asOf,
  generatedAt: new Date().toISOString().slice(0, 10),
  items
};

for (const [k, r] of Object.entries(items)) {
  console.log(`${k.padEnd(16)} ${String(r.direction).padEnd(9)} ${String(r.confidence).padEnd(9)} score=${r.score} agree=${r.agreement} fresh=${r.freshness_weeks}w${r.under_review ? ' [under review]' : ''}`);
}
if (skipped.length) console.log('skipped:', skipped.join(', '));

// Browser seeds for the Pressure Lab (no fetch): the engine reads the exact
// manifest CI recomputes against, plus the live observation vector to reset to.
// Neither carries a price — same honest inputs the gate already trusts.
function umd(varName, globalName, value) {
  return `/* GENERATED by scripts/build-cost-pressure.mjs — do not edit by hand.\n` +
    ` * Sets window.${globalName}; loaded same-origin so the Pressure Lab stays no-fetch.\n */\n` +
    `(function (root) {\n  'use strict';\n  var ${varName} = ${JSON.stringify(value, null, 2)};\n` +
    `  if (typeof module !== 'undefined' && module.exports) module.exports = ${varName};\n` +
    `  if (typeof self !== 'undefined') self.${globalName} = ${varName};\n` +
    `  if (root) root.${globalName} = ${varName};\n` +
    `})(typeof window !== 'undefined' ? window : (typeof self !== 'undefined' ? self : null));\n`;
}
const liveSeed = { _doc: 'Live observation vector + anchor dates for the Pressure Lab — % changes only, never a price.', status, asOf: obsDoc.asOf, anchor: anchors, observations: liveObs };

// Track record: append this run's call per item (deduped by asOf), score the
// PRIOR call once the measured anchor advances (a hit/miss vs the realized
// trend), and let the regime-breaker suppress an item on a cold streak. The
// log can't be backfilled — it accrues from here. Direction/score only, no price.
let history = { _doc: 'Pressure call track record — predicted direction vs the realized measured trend, scored once the next price prints. No price. Append-only, capped.', _version: rules._version, items: {} };
try { const prev = rd('data/pressure-history.json'); if (prev && prev.items) history.items = prev.items; } catch { /* first run */ }
for (const [item, rec] of Object.entries(items)) {
  const arr = history.items[item] = history.items[item] || [];
  const last = arr[arr.length - 1];
  const curAnchor = rec.anchor_print_date;
  const realizedDir = (ci[item] && ci[item].points && ci[item].points[0] && ci[item].points[0].trend && ci[item].points[0].trend.dir) || null;
  // A new measured print since the last recorded call → that call is now scorable.
  if (last && last.anchor && curAnchor && last.anchor !== curAnchor && last.realized == null) last.realized = realizedDir;
  if (!last || last.asOf !== rec.as_of) {
    // Persist the point-in-time observation vector (% changes only) alongside the
    // call. This is the seed the calibration harness validates against over time —
    // what the panel actually saw on each date, not just the direction it produced.
    arr.push({ asOf: rec.as_of, anchor: curAnchor, direction: rec.direction, score: rec.score, realized: null, obs: obsDoc.observations[item] || {} });
    while (arr.length > 52) arr.shift();
  }
  // Regime-breaker: a cold streak flags the item under review (the renderer shows
  // "awaiting the next price"). We set ONLY under_review — never overriding the
  // raw direction/confidence/score — so check-pressure-honesty's recompute still
  // matches. Inert until calls are scored.
  const pairs = arr.filter((e) => e.realized).map((e) => ({ predicted: e.direction, realized: e.realized }));
  if (Accuracy.shouldSuppress(pairs)) rec.under_review = true;
  const acc = Accuracy.scoreCalls(pairs);
  if (acc.n) rec.track_record = { n: acc.n, hits: acc.hits, hitRate: acc.hitRate };
}

if (DRY) { console.log(`(dry-run) ${built} pressure record(s) + 2 Lab seed(s).`); }
else {
  writeFileSync(path.join(repoRoot, 'data/cost-pressure.json'), JSON.stringify(out, null, 2) + '\n');
  writeFileSync(path.join(repoRoot, 'data/pressure-rules.js'), umd('RULES', 'MUNTIN_PRESSURE_RULES', rules));
  writeFileSync(path.join(repoRoot, 'data/pressure-live.js'), umd('LIVE', 'MUNTIN_PRESSURE_LIVE', liveSeed));
  writeFileSync(path.join(repoRoot, 'data/pressure-history.json'), JSON.stringify(history, null, 2) + '\n');
  console.log(`Wrote data/cost-pressure.json + pressure-rules.js + pressure-live.js + pressure-history.json (status=${status}, ${built} record(s)).`);
}
