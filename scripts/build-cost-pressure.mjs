#!/usr/bin/env node
/**
 * build-cost-pressure.mjs — run the deterministic Pressure engine
 * (tools/_shared/cost-pressure.js) over data/pressure-rules.json + observations,
 * writing data/cost-pressure.json: one INFERRED-direction record per ingredient.
 *
 * THE RECORD HAS NO PRICE. It carries direction / confidence / contributors and
 * points AT the measured anchor (its last print date, read from
 * data/cost-index.json) so the overlay can show "as of" honesty. Pressure is
 * only built for ingredients that already ship a measured reading (the anchor) —
 * an overlay with no anchor would be a forecast floating free, which we don't do.
 *
 * Preview vs live:
 *   - observations from data/pressure-observations.demo.json → status 'preview'.
 *   - (P2) live observations from the free fetchers → status 'live'.
 *
 *   node scripts/build-cost-pressure.mjs            # write
 *   node scripts/build-cost-pressure.mjs --dry-run  # print, don't write
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const { assess } = require(path.join(repoRoot, 'tools/_shared/cost-pressure.js'));
const { isShippable } = require(path.join(repoRoot, 'tools/_shared/cost-confidence.js'));
const DRY = process.argv.includes('--dry-run');
const rd = (p) => JSON.parse(readFileSync(path.join(repoRoot, p), 'utf8'));

const rules = rd('data/pressure-rules.json');
const obsDoc = rd('data/pressure-observations.demo.json');
const ci = (rd('data/cost-index.json').ingredients) || {};
const defaults = rules.defaults || {};
const status = obsDoc._status || 'preview';

const items = {};
let built = 0, skipped = [];
for (const [item, panelIn] of Object.entries(rules.items || {})) {
  const point = (ci[item] && ci[item].points && ci[item].points[0]) || null;
  // No measured anchor (or below the shippable bar) → no overlay; pressure never floats free.
  if (!point || !isShippable(point)) { skipped.push(item + ' (no shippable anchor)'); continue; }
  const obs = obsDoc.observations[item];
  if (!obs) { skipped.push(item + ' (no observations)'); continue; }
  const observations = {};
  for (const [id, changePct] of Object.entries(obs)) observations[id] = { changePct, asOf: obsDoc.asOf };
  const panel = Object.assign({}, defaults, panelIn, { item, rule_version: panelIn.rule_version || rules._version });
  const rec = assess(panel, observations, { anchorPrintDate: point.asOf || null, asOf: obsDoc.asOf, ruleVersion: rules._version });
  items[item] = rec;
  built++;
}

const out = {
  _doc: 'GENERATED by scripts/build-cost-pressure.mjs from data/pressure-rules.json + observations. INFERRED direction only — no price. Enforced by scripts/check-pressure-honesty.mjs (recompute-and-compare).',
  _version: rules._version,
  status,
  asOf: obsDoc.asOf,
  generatedAt: new Date().toISOString().slice(0, 10),
  items
};

for (const [k, r] of Object.entries(items)) {
  console.log(`${k.padEnd(16)} ${String(r.direction).padEnd(9)} ${String(r.confidence).padEnd(9)} score=${r.score} agree=${r.agreement} fresh=${r.freshness_weeks}w${r.under_review ? ' [under review]' : ''}`);
}
if (skipped.length) console.log('skipped:', skipped.join(', '));

if (DRY) { console.log(`(dry-run) ${built} pressure record(s).`); }
else { writeFileSync(path.join(repoRoot, 'data/cost-pressure.json'), JSON.stringify(out, null, 2) + '\n'); console.log(`Wrote data/cost-pressure.json (status=${status}, ${built} record(s)).`); }
