#!/usr/bin/env node
/**
 * Operator Sheets · centralized benchmarks generator (Phase B1).
 *
 * Reads data/benchmarks.json and writes assets/js/sheet-benchmarks.gen.js.
 * The generated module exposes:
 *
 *   window.Bench.evaluate(metric, value)
 *     → { band: 'good'|'warn'|'bad'|'idle', msg }  (locale-aware via <html lang>)
 *
 *   window.Bench.flag(slug, outputs)
 *     → [ string ]  (anomaly messages, locale-aware)
 *
 * Sheet fragments may collapse hardcoded threshold ladders to a
 * single Bench.evaluate() call — updating the canonical band here
 * cascades to every fragment automatically.
 *
 * MUST run BEFORE scripts/build-sheet-pages.mjs (which embeds the
 * versioned <script src> tag into each sheet) — see the build chain
 * in wrangler.jsonc.
 *
 *   node scripts/build-sheet-benchmarks.mjs           # rewrite the .gen.js
 *   node scripts/build-sheet-benchmarks.mjs --check   # exit 1 on diff
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const REPO       = path.resolve(path.dirname(__filename), '..');
const checkOnly  = process.argv.includes('--check');

const SRC_PATH = path.join(REPO, 'data', 'benchmarks.json');
const OUT_PATH = path.join(REPO, 'assets', 'js', 'sheet-benchmarks.gen.js');

const data = JSON.parse(fs.readFileSync(SRC_PATH, 'utf8'));

// Validation: every threshold has lt + band + msg_en + msg_es; each
// metric ends with a sentinel band (lt: 999 or similar). Anomaly
// rules name a sheet slug and a known op.
const errors = [];
for (const [metric, def] of Object.entries(data.metrics || {})) {
  const ths = def.thresholds || [];
  if (!ths.length) errors.push(`metric "${metric}" has no thresholds`);
  for (const t of ths) {
    if (typeof t.lt !== 'number') errors.push(`metric "${metric}" threshold missing lt: ${JSON.stringify(t)}`);
    if (!t.band) errors.push(`metric "${metric}" threshold missing band`);
    if (!t.msg_en || !t.msg_es) errors.push(`metric "${metric}" threshold missing msg_en/msg_es`);
  }
}
const allowedOps = new Set(['lt', 'lte', 'gt', 'gte', 'eq', 'neq']);
for (const a of data.anomalies || []) {
  if (!a.slug || !a.when) errors.push(`anomaly missing slug/when: ${JSON.stringify(a)}`);
  if (a.when && !allowedOps.has(a.when.op)) errors.push(`anomaly op "${a.when.op}" not in ${[...allowedOps]}`);
  if (!a.say_en || !a.say_es) errors.push(`anomaly missing say_en/say_es: ${JSON.stringify(a)}`);
}
if (errors.length) {
  console.error('benchmarks.json validation failed:');
  for (const e of errors) console.error('  - ' + e);
  process.exit(2);
}

// Build a stable, indented JSON-string for the generated module.
const generated = `/* Auto-generated by scripts/build-sheet-benchmarks.mjs from
 * data/benchmarks.json. DO NOT EDIT BY HAND.
 *
 * Public API:
 *   window.Bench.evaluate(metric, value) → { band, msg }
 *   window.Bench.flag(slug, outputs)     → [string]
 *
 * Locale resolved from <html lang> at first call.
 */
(function () {
  'use strict';
  if (window.Bench) return;
  var DATA = ${JSON.stringify(data, null, 2)};
  function locale() {
    var lang = (document.documentElement.getAttribute('lang') || 'en').toLowerCase();
    return lang.indexOf('es') === 0 ? 'es' : 'en';
  }
  function pickMsg(t) {
    return locale() === 'es' ? t.msg_es : t.msg_en;
  }
  function evaluate(metric, value) {
    var def = DATA.metrics && DATA.metrics[metric];
    if (!def || typeof value !== 'number' || !isFinite(value)) {
      return { band: 'idle', msg: '' };
    }
    var ths = def.thresholds || [];
    for (var i = 0; i < ths.length; i++) {
      if (value < ths[i].lt) return { band: ths[i].band, msg: pickMsg(ths[i]) };
    }
    var last = ths[ths.length - 1];
    return { band: last.band, msg: pickMsg(last) };
  }
  function compare(op, a, b) {
    switch (op) {
      case 'lt':  return a < b;
      case 'lte': return a <= b;
      case 'gt':  return a > b;
      case 'gte': return a >= b;
      case 'eq':  return a === b;
      case 'neq': return a !== b;
    }
    return false;
  }
  function flag(slug, outputs) {
    var anomalies = DATA.anomalies || [];
    var out = [];
    for (var i = 0; i < anomalies.length; i++) {
      var a = anomalies[i];
      if (a.slug !== slug) continue;
      var when = a.when;
      if (!when || !(when.field in outputs)) continue;
      var v = outputs[when.field];
      if (typeof v !== 'number') v = parseFloat(String(v).replace(/[$,%\\s]/g, ''));
      if (!isFinite(v)) continue;
      if (compare(when.op, v, when.rhs)) {
        out.push(locale() === 'es' ? a.say_es : a.say_en);
      }
    }
    return out;
  }
  window.Bench = { evaluate: evaluate, flag: flag };
})();
`;

const prev = fs.existsSync(OUT_PATH) ? fs.readFileSync(OUT_PATH, 'utf8') : '';
if (prev === generated) {
  console.log('Sheet benchmarks: no changes.');
  process.exit(0);
}
if (!checkOnly) fs.writeFileSync(OUT_PATH, generated);
console.log(`${checkOnly ? 'would write' : 'wrote'}: ${path.relative(REPO, OUT_PATH)}  (${(generated.length / 1024).toFixed(1)} KB uncompressed)`);
if (checkOnly) process.exit(1);
