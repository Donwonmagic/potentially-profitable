#!/usr/bin/env node
/**
 * Phase F.1 (Field Notes) — inject reader-submitted field notes into
 * blog article pages.
 *
 * Reads data/article-fieldnotes.json. For each article slug with
 * approved entries, finds the corresponding article page
 * (blog/<slug>/index.html for EN, es/blog/<slug>/index.html for
 * ES) and stamps a stack of .callout--field blocks between
 * sentinels:
 *
 *   <!-- field-notes:start -->
 *   <div class="field-notes-container">
 *     <aside class="callout callout--field">
 *       <p class="callout-eyebrow">Field note from {author}</p>
 *       <p class="callout-body">…</p>
 *       <p class="callout-body"><span class="callout-eyebrow-inline">Don adds —</span> …optional…</p>
 *     </aside>
 *     <aside class="callout callout--field">
 *       …next note…
 *     </aside>
 *   </div>
 *   <!-- field-notes:end -->
 *
 * If the sentinel pair already exists, replace content between
 * them. If missing, insert immediately AFTER
 * <aside class="post-end-mark"> and BEFORE
 * <!-- post-end-cta:start -->.
 *
 * Body is escapeHtml'd at render even though it's already escaped
 * at decision-time write (defense in depth, mirrors the glossary
 * fieldnotes pattern).
 *
 * Locale-tolerant: an article may have EN-only or ES-only notes;
 * the script touches only the locales that have entries. Mirrors
 * inject-glossary-fieldnotes.mjs's tolerance.
 *
 * Side effect: also writes src/lib/article-slugs.generated.js with
 * the allowlist of valid article slugs (used by the F.3 server
 * endpoints to validate submission requests). Idempotent — same
 * input produces the same output.
 *
 * Usage:
 *   node scripts/inject-article-fieldnotes.mjs           # rewrite in place
 *   node scripts/inject-article-fieldnotes.mjs --check   # exit 1 if any change
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const repoRoot   = path.resolve(path.dirname(__filename), '..');
const checkOnly  = process.argv.includes('--check');

const dataPath = path.join(repoRoot, 'data', 'article-fieldnotes.json');
const data     = JSON.parse(fs.readFileSync(dataPath, 'utf8'));
const fieldnotes = data.fieldnotes || {};

const SENTINEL_RE = /<!-- field-notes:start -->[\s\S]*?<!-- field-notes:end -->/;
const POST_END_MARK_RE = /<aside class="post-end-mark">[\s\S]*?<\/aside>/;
const POST_END_CTA_START = '<!-- post-end-cta:start -->';

const LOCALES = [
  { code: 'en', dir: 'blog',    peopleBase: '/people/',    eyebrowPrefix: 'Field note from', donsLeadin: 'Don adds —' },
  { code: 'es', dir: 'es/blog', peopleBase: '/es/people/', eyebrowPrefix: 'Apunte de',       donsLeadin: 'Don añade —' },
];

function escapeHtml(s) {
  return String(s == null ? '' : s).replace(/[&<>]/g, (c) => ({ '&':'&amp;','<':'&lt;','>':'&gt;' })[c]);
}

// Slug match build-people-pages.mjs slugify().
function slugifyAuthor(s) {
  return String(s)
    .toLowerCase()
    .normalize('NFD').replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60);
}

function renderOneNote(note, locale) {
  const author = note.author || 'a reader';
  const slug = slugifyAuthor(author);
  // Phase F.7: wrap author name in a link to their contributor page
  // when the slug resolves. The contributor page is generated by
  // build-people-pages.mjs from the same data; the link is stable.
  const authorHtml = slug
    ? `<a class="callout-author-link" href="${locale.peopleBase}${slug}/">${escapeHtml(author)}</a>`
    : escapeHtml(author);
  const eyebrow = `${locale.eyebrowPrefix} ${authorHtml}`;
  const lines = [
    '      <aside class="callout callout--field">',
    `        <p class="callout-eyebrow">${eyebrow}</p>`,
    `        <p class="callout-body">${escapeHtml(note.body)}</p>`,
  ];
  if (note.donsResponse && String(note.donsResponse).trim()) {
    lines.push(
      `        <p class="callout-body"><span class="callout-eyebrow-inline">${escapeHtml(locale.donsLeadin)}</span> ${escapeHtml(note.donsResponse)}</p>`
    );
  }
  lines.push('      </aside>');
  return lines.join('\n');
}

function renderBlock(notes, locale) {
  if (!notes || !notes.length) return null;
  const inner = notes.map((n) => renderOneNote(n, locale)).join('\n');
  return [
    '<!-- field-notes:start -->',
    '      <div class="field-notes-container">',
    inner,
    '      </div>',
    '      <!-- field-notes:end -->',
  ].join('\n      ');
}

function injectArticleFieldnotes(file, notes, locale) {
  const src = fs.readFileSync(file, 'utf8');
  const block = renderBlock(notes, locale);
  if (!block) return false; // no notes this locale; nothing to do

  let next;
  if (SENTINEL_RE.test(src)) {
    next = src.replace(SENTINEL_RE, block);
  } else {
    // First-time insert: after the post-end-mark aside, before
    // post-end-cta:start. Fallback to just-before-cta-start when an
    // article ships without the decorative post-end-mark.
    if (src.includes(POST_END_CTA_START)) {
      const insertion = `\n      ${block}\n      `;
      next = src.replace(POST_END_CTA_START, insertion + POST_END_CTA_START);
    } else {
      console.warn(`  warn: ${path.relative(repoRoot, file)} missing post-end-cta:start anchor; skipping`);
      return false;
    }
  }

  if (next === src) return false;
  if (!checkOnly) fs.writeFileSync(file, next);
  console.log(`${checkOnly ? 'would update' : 'updated'}: ${path.relative(repoRoot, file)}`);
  return true;
}

// --- side effect: write article-slugs.generated.js ----------------
//
// The F.3 server endpoints use this allowlist to validate submission
// requests. Generating it here keeps the slug list in lock-step with
// the data file and avoids a second source of truth.
function writeAllowlist() {
  const slugs = Object.keys(fieldnotes).sort();
  const out = [
    '// AUTO-GENERATED by scripts/inject-article-fieldnotes.mjs.',
    '// Do not edit by hand. Regenerate by running the script.',
    '// Source: data/article-fieldnotes.json',
    '',
    'export const ARTICLE_SLUGS = Object.freeze([',
    ...slugs.map((s) => `  ${JSON.stringify(s)},`),
    ']);',
    '',
  ].join('\n');
  const target = path.join(repoRoot, 'src', 'lib', 'article-slugs.generated.js');
  const prev = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (prev === out) return false;
  if (!checkOnly) fs.writeFileSync(target, out);
  console.log(`${checkOnly ? 'would update' : 'updated'}: ${path.relative(repoRoot, target)}`);
  return true;
}

let changed = 0;
let skipped = 0;
const missing = [];

for (const [slug, perLocale] of Object.entries(fieldnotes)) {
  for (const locale of LOCALES) {
    const notes = perLocale[locale.code];
    if (!notes || !notes.length) continue;
    const file = path.join(repoRoot, locale.dir, slug, 'index.html');
    if (!fs.existsSync(file)) {
      missing.push(`${locale.dir}/${slug}/index.html`);
      continue;
    }
    if (injectArticleFieldnotes(file, notes, locale)) changed++;
    else skipped++;
  }
}

if (writeAllowlist()) changed++;

if (missing.length) {
  console.warn(`\n${missing.length} article page(s) referenced in data/article-fieldnotes.json but missing on disk:`);
  for (const m of missing) console.warn(`  ${m}`);
}

console.log(`\n${checkOnly ? 'would update' : 'updated'} ${changed} file(s); ${skipped} unchanged.`);

if (checkOnly && changed > 0) process.exit(1);
