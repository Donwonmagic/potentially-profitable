#!/usr/bin/env node
// Re-stamp the glossary per-term URL block inside sitemap.xml between
//   <!-- glossary-term-urls:start --> ... <!-- glossary-term-urls:end -->
// sentinels. One <url> entry per term directory under /glossary/, with
// hreflang alternates pointing at /es/glossary/<slug>/ when an ES
// counterpart exists. Idempotent — safe to re-run after adding /
// renaming terms.
//
// Per-term entries get priority 0.5 (below the index at 0.7) and a
// monthly changefreq, matching how other long-tail leaves are listed.
// lastmod is the file's mtime in YYYY-MM-DD form, so a content edit
// to /glossary/<slug>/index.html naturally bumps it on the next run.
//
//   node scripts/inject-glossary-sitemap.mjs           # rewrites sitemap.xml
//   node scripts/inject-glossary-sitemap.mjs --check   # exits non-zero if anything would change

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const REPO       = path.resolve(path.dirname(__filename), '..');
const checkOnly  = process.argv.includes('--check');

const SENTINEL_OPEN  = '<!-- glossary-term-urls:start (generated by scripts/inject-glossary-sitemap.mjs) -->';
const SENTINEL_CLOSE = '<!-- glossary-term-urls:end -->';
const SENTINEL_RE = new RegExp(
  `${SENTINEL_OPEN.replace(/[-/\\^$*+?.()|[\]{}]/g, '\\$&')}[\\s\\S]*?${SENTINEL_CLOSE.replace(/[-/\\^$*+?.()|[\]{}]/g, '\\$&')}`
);

function listTermSlugs(rel) {
  const dir = path.join(REPO, rel);
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isDirectory() && fs.existsSync(path.join(dir, e.name, 'index.html')))
    .map((e) => e.name)
    .sort();
}

// Section landing pages live at /glossary/<section-slug>/ alongside
// per-term pages. Slugs are stable IDs from data/library-tags.json's
// glossary_section_to_topics keys, kept here in declaration order so
// sitemap entries appear in a natural reading sequence rather than
// alphabetical (which would scatter related sections like
// restaurant-numbers and operations across the file).
const SECTION_SLUGS = [
  'basics',
  'mobile',
  'conversions',
  'trust',
  'findability',
  'subtypes',
  'restaurant-numbers',
  'data-literacy',
  'brand-design',
];

function lastMod(rel) {
  const fp = path.join(REPO, rel, 'index.html');
  if (!fs.existsSync(fp)) return null;
  return fs.statSync(fp).mtime.toISOString().slice(0, 10);
}

// listTermSlugs walks every directory; remove section slugs so we
// don't double-list section landing pages as if they were terms.
// Section pages get listed first in declaration order below.
const SECTION_SLUG_SET = new Set(SECTION_SLUGS);
const allEn  = listTermSlugs('glossary');
const allEs  = listTermSlugs('es/glossary');
const enSlugs = allEn.filter((s) => !SECTION_SLUG_SET.has(s));
const esSlugs = new Set(allEs.filter((s) => !SECTION_SLUG_SET.has(s)));
const enSectionSlugs = SECTION_SLUGS.filter((s) => allEn.includes(s));
const esSectionSlugs = new Set(SECTION_SLUGS.filter((s) => allEs.includes(s)));

const lines = [];

// Section landing pages first (top of the per-glossary block).
for (const slug of enSectionSlugs) {
  const enUrl  = `https://muntin.digital/glossary/${slug}/`;
  const enLast = lastMod(`glossary/${slug}`);
  const hasEs  = esSectionSlugs.has(slug);

  lines.push('  <url>');
  lines.push(`    <loc>${enUrl}</loc>`);
  if (enLast) lines.push(`    <lastmod>${enLast}</lastmod>`);
  lines.push('    <changefreq>monthly</changefreq>');
  lines.push('    <priority>0.6</priority>');
  if (hasEs) {
    lines.push(`    <xhtml:link rel="alternate" hreflang="en" href="${enUrl}" />`);
    lines.push(`    <xhtml:link rel="alternate" hreflang="es" href="https://muntin.digital/es/glossary/${slug}/" />`);
    lines.push(`    <xhtml:link rel="alternate" hreflang="x-default" href="${enUrl}" />`);
  }
  lines.push('  </url>');

  if (hasEs) {
    const esUrl  = `https://muntin.digital/es/glossary/${slug}/`;
    const esLast = lastMod(`es/glossary/${slug}`);
    lines.push('  <url>');
    lines.push(`    <loc>${esUrl}</loc>`);
    if (esLast) lines.push(`    <lastmod>${esLast}</lastmod>`);
    lines.push('    <changefreq>monthly</changefreq>');
    lines.push('    <priority>0.6</priority>');
    lines.push(`    <xhtml:link rel="alternate" hreflang="en" href="${enUrl}" />`);
    lines.push(`    <xhtml:link rel="alternate" hreflang="es" href="${esUrl}" />`);
    lines.push(`    <xhtml:link rel="alternate" hreflang="x-default" href="${enUrl}" />`);
    lines.push('  </url>');
  }
}

// Per-term pages.
for (const slug of enSlugs) {
  const enUrl = `https://muntin.digital/glossary/${slug}/`;
  const enLast = lastMod(`glossary/${slug}`);
  const hasEs  = esSlugs.has(slug);

  lines.push('  <url>');
  lines.push(`    <loc>${enUrl}</loc>`);
  if (enLast) lines.push(`    <lastmod>${enLast}</lastmod>`);
  lines.push('    <changefreq>monthly</changefreq>');
  lines.push('    <priority>0.5</priority>');
  if (hasEs) {
    lines.push(`    <xhtml:link rel="alternate" hreflang="en" href="${enUrl}" />`);
    lines.push(`    <xhtml:link rel="alternate" hreflang="es" href="https://muntin.digital/es/glossary/${slug}/" />`);
    lines.push(`    <xhtml:link rel="alternate" hreflang="x-default" href="${enUrl}" />`);
  }
  lines.push('  </url>');

  if (hasEs) {
    const esUrl = `https://muntin.digital/es/glossary/${slug}/`;
    const esLast = lastMod(`es/glossary/${slug}`);
    lines.push('  <url>');
    lines.push(`    <loc>${esUrl}</loc>`);
    if (esLast) lines.push(`    <lastmod>${esLast}</lastmod>`);
    lines.push('    <changefreq>monthly</changefreq>');
    lines.push('    <priority>0.5</priority>');
    lines.push(`    <xhtml:link rel="alternate" hreflang="en" href="${enUrl}" />`);
    lines.push(`    <xhtml:link rel="alternate" hreflang="es" href="${esUrl}" />`);
    lines.push(`    <xhtml:link rel="alternate" hreflang="x-default" href="${enUrl}" />`);
    lines.push('  </url>');
  }
}

const replacement = `${SENTINEL_OPEN}\n${lines.join('\n')}\n  ${SENTINEL_CLOSE}`;

const sitemapPath = path.join(REPO, 'sitemap.xml');
const src = fs.readFileSync(sitemapPath, 'utf8');
if (!SENTINEL_RE.test(src)) {
  console.error('sitemap.xml is missing the glossary-term-urls sentinels. Add this between');
  console.error('the /glossary/ <url> entry and the next entry:');
  console.error(`  ${SENTINEL_OPEN}\n  ${SENTINEL_CLOSE}`);
  process.exit(2);
}
const next = src.replace(SENTINEL_RE, replacement);

if (next === src) {
  console.log('sitemap.xml: no changes (term URLs already up to date).');
  process.exit(0);
}

if (checkOnly) {
  console.error('sitemap.xml would change. Run: node scripts/inject-glossary-sitemap.mjs');
  process.exit(1);
}

fs.writeFileSync(sitemapPath, next);
console.log(`sitemap.xml: stamped ${enSectionSlugs.length} EN + ${esSectionSlugs.size} ES section URL(s); ${enSlugs.length} EN + ${esSlugs.size} ES term URL(s).`);
