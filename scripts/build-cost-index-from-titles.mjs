#!/usr/bin/env node
/**
 * build-cost-index-from-titles.mjs — emit the ?from continuity title map (Move 9).
 *
 * Tools can't fetch (check-tool-no-fetch), so the closed slug->{en,es} map has to be
 * a same-origin <script>. cost-pulse already carries it via the seed; plate-cost does
 * NOT load the seed, so this generates a tiny standalone module from the committed,
 * fact-gated source of truth: data/cost-index-labels.json#labels. Names only — no
 * units, no prices, no market data — so it never touches the basis-leak surface.
 *
 *   node scripts/build-cost-index-from-titles.mjs           # write the module
 *   node scripts/build-cost-index-from-titles.mjs --check   # exit 1 if out of date
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(repoRoot, 'data/cost-index-labels.json');
const OUT = path.join(repoRoot, 'tools/_shared/cost-index-from-titles.js');
const checkOnly = process.argv.includes('--check');

const labels = JSON.parse(fs.readFileSync(SRC, 'utf8')).labels || {};

// Slug-shaped keys with both languages only — mirrors the runtime guard's closed set
// and the seed builder's "drop any label-less ingredient" rule, so the two stay in sync.
const map = {};
for (const slug of Object.keys(labels).sort()) {
  if (!/^[a-z0-9-]{1,40}$/.test(slug)) continue;
  const e = labels[slug];
  if (!e || typeof e.en !== 'string' || typeof e.es !== 'string' || !e.en || !e.es) continue;
  map[slug] = { en: e.en, es: e.es };
}

const body = `/**
 * cost-index-from-titles.js — GENERATED by scripts/build-cost-index-from-titles.mjs.
 * Do NOT hand-edit. The closed slug -> {en,es} title map for the ?from continuity
 * line (Move 9), sourced from the fact-gated data/cost-index-labels.json. Names only,
 * zero market data. ${Object.keys(map).length} slugs. Frozen so it can't be mutated at runtime.
 */
(function (root) {
  'use strict';
  var MAP = Object.freeze(${JSON.stringify(map)});
  if (typeof module !== 'undefined' && module.exports) module.exports = MAP;
  if (typeof self !== 'undefined') self.MUNTIN_FROM_TITLES = MAP;
  if (root) root.MUNTIN_FROM_TITLES = MAP;
})(typeof window !== 'undefined' ? window : (typeof self !== 'undefined' ? self : null));
`;

if (checkOnly) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== body) {
    console.error(`cost-index-from-titles: OUT of date — run \`node scripts/build-cost-index-from-titles.mjs\`.`);
    process.exit(1);
  }
  console.log(`cost-index-from-titles: up to date (${Object.keys(map).length} slugs).`);
  process.exit(0);
}

fs.writeFileSync(OUT, body);
console.log(`cost-index-from-titles: wrote ${path.relative(repoRoot, OUT)} (${Object.keys(map).length} slugs).`);
