#!/usr/bin/env node
/**
 * Phase SEO — auto-stamp `id` attributes on every <h2> in long-form
 * articles so AI search (Google AI Overview, Perplexity, ChatGPT
 * citations) and direct readers can deep-link to a section instead of
 * the article root. Without ids, an AI citation has to land on the
 * article and the reader scrolls to find the relevant heading; with
 * ids, AI assistants link straight to `…/blog/<slug>/#the-three-shifts`.
 *
 * Approach
 *   - Walk blog/ + es/blog/ + glossary/ + es/glossary/ + learn/ + es/learn/
 *     (long-form surfaces; tools / sheets / studio have their own H2
 *     conventions and are skipped).
 *   - For every <h2> WITHOUT an `id` attribute, slugify the inner text
 *     and stamp it. Slugifier: lowercase ASCII, replace non-alnum with
 *     hyphens, strip leading/trailing hyphens, dedupe consecutive
 *     hyphens, truncate to 60 chars.
 *   - If a stamped id would collide with an existing id on the same
 *     page, suffix `-2`, `-3`, etc. until unique.
 *   - Idempotent: <h2 id="..."> is left alone (matches the existing-id
 *     case explicitly).
 *
 * SEO rationale
 *   AI Overview, Perplexity, and ChatGPT all surface their citations
 *   with anchor URLs when the source page has them. Section anchors
 *   give the citation a stable target ("according to muntin.digital,
 *   #the-cost-of-the-call-button-disappearing, …"). Without the id,
 *   the citation has to land on the article URL and the AI generates
 *   a "see the section" footer that operators have to hunt for. Free
 *   ranking + click-through signal.
 *
 * Usage
 *   node scripts/inject-h2-anchor-ids.mjs           # rewrite in place
 *   node scripts/inject-h2-anchor-ids.mjs --check   # exit 1 if any
 *                                                     <h2> would get
 *                                                     a new id
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const REPO       = path.resolve(path.dirname(__filename), '..');
const checkOnly  = process.argv.includes('--check');

// Only stamp ids on long-form article surfaces. The tools / sheets /
// studio H2s are reusable shells whose text changes per-instance and
// whose ids the parent component wants to control directly.
//
// learn/topics/ pages are EXCLUDED — they're regenerated by
// inject-topic-pillar-essay.mjs + inject-topic-sheets-rail.mjs, which
// don't expect <h2> tags carrying our id attribute and oscillate
// against each other if we stamp them. Topic pages are landing pages
// for AI cross-link, not articles AI search engines would deep-cite.
const TARGET_DIRS = [
  'blog',
  'es/blog',
  'glossary',
  'es/glossary',
  'learn/research',
  'es/learn/research',
];

function* walk(dir) {
  if (!fs.existsSync(dir)) return;
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    if (ent.name.startsWith('.') || ent.name === 'node_modules') continue;
    const p = path.join(dir, ent.name);
    if (ent.isDirectory()) yield* walk(p);
    else if (ent.isFile() && p.endsWith('.html')) yield p;
  }
}

// Strip HTML tags so the slug is derived from visible text only.
// Common in-h2 nesting: <span class="serif-italic">italic part</span>,
// <em>emphasized</em>, <code>code</code>, <strong>strong</strong>.
function stripTags(s) {
  return s.replace(/<[^>]+>/g, '').replace(/&[a-z]+;/gi, ' ').replace(/&#\d+;/g, ' ');
}

function slugify(s) {
  return stripTags(s)
    .toLowerCase()
    .normalize('NFD').replace(/[̀-ͯ]/g, '') // strip accents
    .replace(/[^\p{Letter}\p{Number}]+/gu, '-')
    .replace(/^-+|-+$/g, '')
    .replace(/-+/g, '-')
    .slice(0, 60)
    .replace(/-+$/, '');
}

// Match opening <h2> tags, capturing the existing attribute span (if
// any) and the inner text up to </h2>. Anchored so we never cross an
// </h2> boundary inside the lazy [\s\S]*?.
const H2_RE = /<h2\b([^>]*)>([\s\S]*?)<\/h2>/g;

// Existing id="…" within the captured attribute span, used to decide
// whether to leave the tag alone (idempotency).
const ID_ATTR_RE = /\bid\s*=\s*"[^"]*"/;

let scanned = 0;
let stamped = 0;
const pendingFiles = [];

for (const dir of TARGET_DIRS) {
  for (const f of walk(path.join(REPO, dir))) {
    scanned++;
    const src = fs.readFileSync(f, 'utf8');

    // Collect ALL existing ids on the page so a freshly slugged id
    // collision can dedupe against EVERY id, not just other h2 ids.
    const existingIds = new Set();
    for (const m of src.matchAll(/\bid\s*=\s*"([^"]+)"/g)) {
      existingIds.add(m[1]);
    }

    let changed = false;
    const next = src.replace(H2_RE, (full, attrs, inner) => {
      if (ID_ATTR_RE.test(attrs)) return full; // already has id, leave alone
      const base = slugify(inner);
      if (!base) return full;                    // empty text, can't slug
      let candidate = base;
      let suffix = 2;
      while (existingIds.has(candidate)) {
        candidate = `${base}-${suffix}`;
        suffix++;
      }
      existingIds.add(candidate);
      changed = true;
      stamped++;
      return `<h2${attrs} id="${candidate}">${inner}</h2>`;
    });

    if (changed) {
      if (checkOnly) {
        pendingFiles.push(path.relative(REPO, f));
      } else {
        fs.writeFileSync(f, next);
      }
    }
  }
}

if (checkOnly) {
  if (pendingFiles.length > 0) {
    console.error(`inject-h2-anchor-ids: would stamp ${stamped} h2(s) across ${pendingFiles.length} file(s):`);
    for (const p of pendingFiles.slice(0, 10)) console.error(`  - ${p}`);
    if (pendingFiles.length > 10) console.error(`  … and ${pendingFiles.length - 10} more`);
    process.exit(1);
  }
  console.log(`inject-h2-anchor-ids: no changes (${scanned} files scanned).`);
  process.exit(0);
}

console.log(`inject-h2-anchor-ids: stamped ${stamped} h2 id(s) across ${scanned} long-form files.`);
